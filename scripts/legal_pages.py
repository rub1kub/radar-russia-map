def build() -> list[str]:
    """Записать страницы. Возвращает пути для sitemap."""
    pages = [
        ("/privacy/", "Политика конфиденциальности",
         "Какие данные обрабатывает карта воздушной обстановки «Тихое небо», "
         "зачем и сколько хранит.", PRIVACY_BODY),
        ("/terms/", "Условия использования",
         "Условия использования сервиса «Тихое небо»: агрегатор открытых "
         "источников, не СМИ и не система оповещения.", TERMS_BODY),
    ]
    written = []
    for path, title, description, body in pages:
        directory = OUT / path.strip("/")
        directory.mkdir(parents=True, exist_ok=True)
        (directory / "index.html").write_text(
            shell(title, description, path, body), encoding="utf-8")
        written.append(f"{SITE}{path}")
    return written


def main() -> int:
    for url in build():
        print(f"страница: {url}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
