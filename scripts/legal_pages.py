def shell(title: str, description: str, path: str, body: str) -> str:
    url = f"{SITE}{path}"
    structured_data = json.dumps({
        "@context": "https://schema.org",
        "@type": "WebPage",
        "url": url,
        "name": title,
        "description": description,
        "inLanguage": "ru-RU",
        "isPartOf": {"@type": "WebSite", "name": "Тихое небо",
                     "url": f"{SITE}/"},
    }, ensure_ascii=False)
    return f"""<!doctype html>
<html lang="ru">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>{escape(title)} · Тихое небо</title>
    <meta name="description" content="{escape(description)}" />
    <link rel="canonical" href="{url}" />
    <meta name="robots" content="index, follow" />
    <script type="application/ld+json">{structured_data}</script>
    <style>{STYLE}</style>
  </head>
  <body>
    <main>
      <nav class="crumbs"><a href="/">Карта обстановки</a> → {escape(title)}</nav>
      <h1>{escape(title)}</h1>
      <p class="effective">Редакция от {EFFECTIVE.strftime('%d.%m.%Y')}</p>
{body}
      <footer>
        <a href="/">На карту</a> ·
        <a href="/privacy/">Политика конфиденциальности</a> ·
        <a href="/terms/">Условия использования</a>
      </footer>
    </main>
  </body>
</html>
"""


