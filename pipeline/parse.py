# --- Нерелевантное: памятки и методички -------------------------------------
# Вопрос читателю — не сообщение об обстановке. «Краснодар слышали
# взрывы? Да 👍 Нет 👎» — опрос: канал спрашивает, а не утверждает, и
# давал по Краснодару удар девятого уровня. «Услышали пролёт? Есть
# информация для населения?» — та же форма, только канал просит присылать
# новости.
#
# Снимаются именно вопросительные предложения, а не сообщение целиком:
# «Долгоруково — сообщают о пролётах БПЛА. Вы слышали? 👍/👎» содержит и
# настоящее сообщение, и вопрос следом, и терять первое нельзя.
QUESTION_RE = re.compile(r"[^.!?\n]*\?+")


def drop_questions(text: str) -> str:
    """Текст без вопросительных предложений."""
    return QUESTION_RE.sub(" ", text)


