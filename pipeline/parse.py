# Движение К named-зоне: «двигается на Причерноморье», «курс на Сочи»,
# «в вашем направлении». Для зоны-адресата это предупреждение, а не
# наблюдение: борт видели где-то там, а сюда он только идёт. Телеграфный
# запасной разбор ставил таким сообщениям «Фиксацию» — и по Сочи стоял
# красный значок «здесь видят борт» из-за «От 15 БПЛА двигается на
# Причерноморье».
# Компасные направления («на юг», «в тыл») сюда намеренно не входят: это
# курс уже наблюдаемого борта («по трассе Новоайдар-Счастье на юг БПЛА» —
# борт видят на трассе), а не зона-адресат.
#
# Голые «на Краснодар» и «к Краснодару» — та же самая мысль, только без
# глагола: телеграфный язык лент («Калининский район на Краснодар БПЛА»,
# «и близлежащих к Краснодару»). Без них адресат получал «Фиксацию» —
# на Краснодар вешался красный значок «здесь видят борт», хотя все ленты
# писали только о том, что борта в его сторону идут.
#
# Требуется заглавная буква следом: «на юг», «на подлёте», «к утру» —
# не адресаты. Хвосты речных имён исключены явно: «Славянск на Кубани»,
# «Ростов на Дону» пишут и через пробелы, и «на» там часть названия.
# Список закрытый — в справочнике таких зон 21, все на перечисленных
# реках и озёрах.
NAME_TAIL = (r"Дону|Амуре|Кубани|Оби|Волге|Черемшане|Узе|Умбозере"
             r"|Шегарке|Печоре|Еманче|Ухтоме|Дону́")
MOVING_TO_RE = re.compile(
    r"в\s+(?:\w+\s+)?направлени\w*|в\s+сторону\b|курс(?:ом)?\s+на\b"
    r"|двига\w+\s+(?:на|в)\b|прош[лаиё]\w*\s+на\b|ид[её]т\s+на\b"
    r"|лет[ия]т\s+на\b"
    # (?-i:…) обязательно: всё выражение идёт с IGNORECASE, и без снятия
    # флага «[А-ЯЁ]» ловит и строчные — «на юг» и «фпв на оптоволокне»
    # становились адресатами, хотя это компасный курс и способ связи.
    rf"|\bна\s+(?!(?:{NAME_TAIL})\b)(?=(?-i:[А-ЯЁ]))"
    rf"|\bк\s+(?!(?:{NAME_TAIL})\b)(?=(?-i:[А-ЯЁ]))",
    re.IGNORECASE,
)


# Движение К ЧИТАТЕЛЮ: «к вам», «на вас», «в вашу сторону». Названное
# место здесь — адресат, а борт где-то ещё и только идёт сюда. Отдельно
# от MOVING_TO_RE, потому что зоны-получателя в тексте нет: адресат — сам
# канал, и разделить фразу на «наблюдение» и «цель» нечем. Понижаем
# фиксацию до опасности: «Краснодар. Предварительно к вам БПЛА» вешало на
# Краснодар красный значок «здесь видят борт».
#
# Тонкость, которую надо принять осознанно: «Фиксации 2 БПЛА к вам» —
# фиксация действительно была, но НЕ здесь, а там, откуда борт идёт.
# Проверку «убрать оборот и посмотреть, осталась ли фиксация» здесь
# применять нельзя — она бы всё вернула обратно. Поэтому правило простое
# и жёсткое: сказали «к вам» — значит, борт ещё не над вами.
APPROACH_RE = re.compile(
    r"\bк\s+вам\b|\bна\s+вас\b|\bк\s+нам\b|в\s+ваш\w+\s+сторону",
    re.IGNORECASE,
)


# Оговорка о возможном будущем. «Также в случае прорыва БПЛА ожидаются
# ещё цели от напротив Анапского района, Новороссийска, Геленджика» —
# хвост сообщения, которое началось с «Сочи, уничтожена группа БПЛА».
# Сигнал у сообщения один на все названные места, и перехват над Сочи
# расходился перехватом по Анапе, Новороссийску и Геленджику, где ничего
# не сбивали и сбивать пока не собирались.
#
# Отличается от MOVING_TO_RE тем, что говорит не про направление, а про
# условие: борт туда, может, и не пойдёт вовсе.
# Только однозначные зачины условия. «Возможные подвороты к побережью» и
# прочие расплывчатые обороты сюда намеренно не входят: правило липкое
# (см. ниже), и слабый зачин утащил бы за собой настоящие наблюдения.
FORECAST_RE = re.compile(
    r"в\s+случае\b|при\s+прорыв\w*|если\s+прорв\w*"
    r"|ожида\w+\s+(?:ещ[её]\s+)?(?:цел|борт|бпла|дрон|налёт|налет|атак"
    r"|фиксаци|сбити|прил[её]т)\w*",
    re.IGNORECASE,
)


def forecast_phrases(phrases: list[str]) -> list[str]:
    """Фразы-прогнозы: места в них — куда может пойти, а не где есть.

    Правило липкое: от первой оговорки и до конца сообщения. Перечисление
    рвётся на фразы по запятым, и зачин остаётся только в первом куске —
    «Также в случае прорыва БПЛА ожидаются ещё цели от напротив Анапского
    района» / «Новороссийска» / «Геленджика к Туапсе». Без липкости
    прогнозом считалась бы одна Анапа, а Новороссийск с Геленджиком
    получали бы перехват, объявленный в начале сообщения для Сочи.

    Оговорка — конструкция хвостовая: она завершает сообщение, а не
    вклинивается в середину. Если всё же вклинится, ошибка пойдёт в
    сторону осторожности: место получит «опасность» вместо «перехвата».
    """
    for index, phrase in enumerate(phrases):
        if FORECAST_RE.search(phrase):
            return phrases[index:]
    return []


# Хвост сигнала на конце перечисляемого адресата: «Краснодар тревога по
# БПЛА» — сигнал принадлежит сообщению, а не выделяет Краснодар в
# наблюдение. После среза остаётся голое имя.
ENUM_SIGNAL_TAIL_RE = re.compile(
    r"\s+(?:тревог|опасност)\w*(?:\s+\S+)*$", re.IGNORECASE)
# Элемент перечисления — голое имя места: одно-четыре слова с заглавных
# букв, служебные «на/в/и» между ними («Славянск на Кубани»).
ENUM_ITEM_RE = re.compile(
    r"[А-ЯЁ][\w-]*(?:\s+(?:на|в|и)\s+[А-ЯЁ][\w-]*|\s+[А-ЯЁ][\w-]*){0,3}")


def split_directions(phrases: list[str]) -> tuple[list[str], list[str]]:
    """Фразы наблюдения отдельно, адресаты движения отдельно.

    «Мангуш тревога по БПЛА и далее в направлении Азовского моря» — Мангуш
    видит борт, а море его только ждёт. Сигнал у сообщения один на всех,
    и до этого разделения море получало ту же тревогу, что и Мангуш.

    Хвост после оборота движения — адресаты; голова до него — наблюдение.
    «Прошли Ейск в направлении моря»: Ейск остаётся наблюдением.

    Перечисление адресатов режется запятыми на отдельные фразы ещё до
    этого разбора: в «в направлении Тихорецк, Тимашевск, Краснодар»
    адресатом считался один Тихорецк, а Тимашевск с Краснодаром получали
    сигнал наблюдения — и бот слал «Краснодар — тревога» городу, который
    только ждёт борт. Поэтому голые имена сразу после оборота движения
    продолжают список адресатов, пока перечисление не оборвётся фразой
    с собственным содержанием.
    """
    observed: list[str] = []
    targets: list[str] = []
    absorbing = False
    for phrase in phrases:
        match = MOVING_TO_RE.search(phrase)
        if match:
            head = phrase[:match.start()].strip(" ,—-")
            tail = phrase[match.end():].strip(" ,—-")
            if head:
                observed.append(head)
            if tail:
                targets.append(tail)
            absorbing = bool(tail)
            continue
        if absorbing:
            bare = ENUM_SIGNAL_TAIL_RE.sub("", phrase).strip(" ,—-")
            if bare and ENUM_ITEM_RE.fullmatch(bare):
                targets.append(bare)
                # Сигнальный хвост закрывает перечисление: после «Краснодар
                # тревога по БПЛА» новых адресатов не бывает.
                if bare != phrase.strip(" ,—-"):
                    absorbing = False
                continue
            absorbing = False
        observed.append(phrase)
    return observed, targets

