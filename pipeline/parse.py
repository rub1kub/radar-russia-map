# Ожидание фиксаций — не фиксация. «Повышенное внимание по фиксациям БПЛА
# с моря этой ночью» — прогноз: борта ещё никто не видел, а слово
# «фиксациям» делало из предупреждения красное событие со значком
# «здесь видят борт».
ANTICIPATION_RE = re.compile(
    r"внимание\s+по\s+фиксаци\w*"
    # «Возможны фиксации и сбития» — обе половины оборота одним куском:
    # иначе «сбития» оставалось в остатке и снова давало перехват.
    r"|возможн\w+\s+(?:фиксаци\w*(?:\s+и\s+сбити\w*)?|сбити\w*|прил[её]т\w*|удар\w*)"
    # Между «ожидаем» и словом события помещается определение: «ожидаем
    # массовую атаку БПЛА» проходило мимо и становилось фиксацией.
    r"|ожида\w+\s+(?:\w+\s+){0,2}?(?:фиксаци|налёт|налет|атак|сбити"
    r"|удар|прил[её]т|пуск)\w*|фиксаци\w+\s+возможн\w+"
    # «Предполагаемые цели противника: …» — перечень того, куда МОГУТ
    # полететь, а не куда летят.
    r"|предпол[оа]гаем\w+\s+цел\w*|вероятн\w+\s+цел\w*"
    # «Приготовиться к сбитиям», «готовность к возможному обстрелу» —
    # предупреждение перед тем, как что-то начнётся. Слова «сбитиям» и
    # «обстрелу» стояли раньше в очереди сигналов и делали из ожидания
    # состоявшийся перехват и удар.
    r"|(?:приготов\w+|готовност\w*)\s+к\s+(?:возможн\w+\s+)?"
    r"(?:сбити|обстрел|удар|атак|прил[её]т)\w*"
    # «Противник готовит запуски БПЛА» — намерение: борт ещё на земле,
    # а фраза давала фиксацию восьмого уровня.
    r"|готов[ия]т\w*\s+(?:запуск|пуск|удар|атак)\w*",
    re.IGNORECASE,
)

# Признаки состоявшегося перехвата — нужны там же, где и признаки фиксации:
# правило упреждения проверяет, остаётся ли перехват после снятия оборота.
#
# «Ликвидирован» намеренно требует рядом борт: пожарные тоже ликвидируют —
# возгорание, задымление, очаг. «Возгорание на складе под Воронежем
# ликвидировано» давало перехват восьмого уровня там, где речь о потушенном
# пожаре после вчерашнего удара.
# Голого «ПВО» здесь больше нет — намеренно. Оно делало перехватом любое
# упоминание: «Силы ПВО находятся в готовности» (это готовность, борт ещё
# летит), «в обход ПВО» (новость про НАТО), «поставки ракет для ПВО
# сократились» (газета). За неделю 256 сообщений держали перехват только
# на этом слове. ПВО — перехват, когда она РАБОТАЕТ: глагол работы с
# любой стороны и в любой форме («работает ПВО», «ПВО отработало»,
# «работа ПВО»). «Работа ВКС по БПЛА» — те же ленты, тот же смысл.
# «Сбил» и «сбивать» без борта рядом — не перехват: «их сбил автомобиль»
# (ДТП в Мурино) и «их необходимо сбивать» (призыв в новости про НАТО)
# на этом уже горели. Существительные «сбит»/«сбитие» остаются голыми:
# в обиходе лент они только про борта.
INTERCEPT_PATTERN = (
    r"\bсбити\w*|\bсбит\b|уничтожен\w*"
    r"|сби(?:л|ва)\w*[^.\n]{0,25}?(?:бпла|дрон\w*|борт\w*|цел[ьи]\w*|ракет\w*)"
    r"|(?:бпла|дрон\w*|борт\w*|ракет\w*)[^.\n]{0,20}?сби(?:л|ва)\w*"
    r"|пво\s+(?:по\s+бпла|работ\w+|отработ\w+|сбива\w+|вед[её]т|ведут)"
    r"|(?:работ|отработ)\w+\s+(?:пво|вкс)"
    # «Идёт отражение атаки БПЛА» — ПВО работает прямо сейчас, сказанное
    # другими словами. Только настоящее время: «атака была успешно
    # отражена» — пересказ, он остаётся у RECAP_RE.
    r"|ид[её]т\s+отражени\w+"
    r"|ликвидирован\w*\s+(?:\w+\s+){0,2}?(?:бпла|дрон\w*|борт\w*|цел[ьи]\w*|ракет\w*)"
)
INTERCEPT_RE = re.compile(INTERCEPT_PATTERN, re.IGNORECASE)

# Условие, а не событие: «Соблюдайте меры безопасности ПРИ СБИТИЯХ БПЛА» —
# это инструкция на случай, если собьют, а не сообщение о сбитии. Строчка
# стоит подписью в каждом втором сообщении кубанских и крымских лент, и
