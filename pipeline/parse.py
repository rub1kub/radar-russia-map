# над Сочи загорелся значок работы ПВО, когда над Сочи ничего не было —
# событие открылось «Опасностью», а подпись-инструкция подняла его до
# перехвата при слиянии.
#
# «Не снимайте работу ПВО, за это можно получить срок» — тоже не событие,
