"""Разбор текста сообщения в структурированное наблюдение.

Покрывает пять семейств форматов из docs/TARGET_ARCHITECTURE.md §4.
Текст канала — недоверенные данные: разбирается регулярными выражениями,
никогда не исполняется.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

from .textnorm import norm_key

# --- Футеры подписки --------------------------------------------------------
# Однозначные маркеры подписи: встречаются только в футере, длина строки
# роли не играет.
FOOTER_RE = re.compile(
    r"(подписаться|подписка|наш\s+канал|@[a-zA-Z_][a-zA-Z0-9_]{3,}"
    r"|локатор\s+россии|мониторинг\s+кубани|кубанский\s+вестник"
    r"|краснодарский\s+дозор|дозор\s+краснодара|в\s+ма[хx]\b)",
    re.IGNORECASE,
)

# Лента выросла с 12 источников до 74, и у каждого нового канала свой футер.
# Перечислять их по именам бессмысленно, поэтому ловим структурные признаки
# подписи: слово «радар»/«мониторинг» в названии канала, ссылку, зеркало в
# MAX, чат и обратную связь. Проверено по всей базе: в теле сообщений эти
# слова встречаются единицы раз (и там это тоже реклама канала).
# Снимать футер важно не ради чистоты: почти каждый содержит топоним
# («РОДНОЙ БЕЛГОРОД | РАДАР», «Радар ЛНР | Чат»), и geocode принимает его
# за место события, приклеивая чужой город к каждому сообщению канала.
FOOTER_BRAND_RE = re.compile(
    r"(https?://|\bt\.me/|maxln\.ru"
    r"|\bрадар\w*|\bмониторинг\w*|краснодарское\s+небо|ор[её]л\s+тревога"
    r"|\b[mм][aа][xх]\b|\b[mм][aа]кс(?:[еаому])?\b"
    r"|обратн\w+\s+связ|наш\s+чат|мы\s+в\s+telegram|читать\s+в\s+telegram"
    r"|дать\s+нам\s+голос|\bтг\b|по\s+данным\s+канал\w+"
    r"|поддержать\s+канал|слова\s+благодарности)",
    re.IGNORECASE,
)

# Футер — короткая строка-подпись: самый длинный настоящий футер в базе 77
# символов. Длинный абзац, где просто упомянуты «радар» или «обратная связь»,
# это текст сообщения, и вырезать его нельзя.
FOOTER_MAX_LEN = 100

# --- Ожидание отбоя, а не сам отбой -----------------------------------------
# «Оставайтесь в укрытии до сигнала "Отбой"», «укрытия не покидаем до отбоя»,
# «никакого отбоя нет» — это часть АКТИВНОГО оповещения. Без вырезания
# ракетная опасность по Орловской области уходила в allclear с severity 0,
# то есть тревога гасла ровно в момент объявления.
INSTRUCTION_RE = re.compile(
    r"(?:дождит\w+|ждите|жд[ёе]м|ожида\w+|получени[ияе])"
    r"[^\n]{0,30}?(?:отбо\w*|отмен\w+\s+(?:угроз|опасност|тревог))"
    r"|\bдо\s+(?:сигнала\s+)?[«\"']?отбо\w*|\bдо\s+[«\"']?отмены\b"
    r"|отбо\w*\s*(?:не\s+было|нет)|никакого\s+отбоя",
    re.IGNORECASE,
)

# --- Нерелевантное: политические и военные новости --------------------------
NEWS_RE = re.compile(
    r"\b(мид|зеленск\w+|путин\w*|минобороны|санкц\w+|саммит\w*|переговор\w+"
    r"|президент\w*|госдум\w+|заявил\w*|заявля\w+|сообщил\s+журналист"
    r"|написал\s+в\s+своем|подписал\s+закон|медведев\w*|песков\w*|лавров\w*"
    r"|трамп\w*|задержан\w*|росгвард\w+|военкомат\w*)\b",
    re.IGNORECASE,
)

# --- Нерелевантное: оборонная и военно-политическая новость ------------------
# «Полки беспилотных систем созданы в составе ВМФ России», «в состав ВМФ
# войдёт крейсер с гиперзвуковыми ракетами Циркон», «Иран пригрозил нанести
# ракетный удар» — рассказ про вооружение и намерения, а не наблюдение в небе.
# Тип угрозы в таком тексте назван («беспилотных», «ракетный»), глагола
# обстановки нет, и телеграфное правило делало из него detection/4. Места в
# сообщении тоже нет, поэтому событие ложилось на регион самого канала —
# фантомная фиксация БПЛА над Липецкой, Смоленской и Тульской областями.
#
# Ловим не сами слова «ВМФ», «ракета», «полк»: они есть и в оповещениях
# («работа ВКС по БПЛА», «хотят сорвать праздник ВМФ»). Ловим новостной
# оборот вокруг них — род войск как предмет сообщения, поставку техники,
# угрозу третьей страны и поздравление с военной датой.
#
# Названий кораблей («крейсер», «фрегат», «корвет», «подводная лодка») и
# «министра обороны» здесь намеренно нет, хотя оборонная новость их и полна.
# Это существительные, а не обороты: в приморских лентах корабль называют и
# в настоящем наблюдении («БЭК в направлении корвета»), а на Минобороны
# ссылается половина оповещений. Проверено по корпусу: ни одного сообщения
# они не ловят в одиночку — все три новости про «Циркон» уже опознаны по
# «в состав ВМФ» и «получивший наименование», а единственное совпадение с
# «министром обороны» и без того нерелевантно. Пользы нет, риск снять живое
# оповещение есть.
MILITARY_NEWS_RE = re.compile(
    r"в\s+состав\w*\s+(?:вмф|вкс|вмс|вдв|флот\w*|арми\w+|войск\w*)"
    r"|(?:созда\w+|сформирова\w+|развернут\w+)\s+в\s+составе"
    r"|\bглавком\w*|\bгенштаб\w*"
    r"|принят\w*\s+на\s+вооружени|поступ\w+\s+в\s+войск|встал\w*\s+на\s+боево"
    r"|получивш\w+\s+наименовани|пригроз\w+|намерен\w*\s+нанести"
    r"|поздравля\w+|\bс\s+праздником\b|\bс\s+дн[её]м\b|\bдень\s+военно",
    re.IGNORECASE,
)

# --- Нерелевантное: чужая сторона -------------------------------------------
# Сводки об ударах по Украине и ближневосточные новости приходят в те же
# ленты. Слова «прилёт», «пожар», «сбит» в них есть, а класть их на карту
# воздушной обстановки России некуда.
#
# Одного слова для опознания мало. Под «николаев\w*» в справочнике 543
# российские зоны (одна Николаевка встречается 309 раз), под «львов\w*» — 54,
# под «чернигов\w*» — 47: станица Львовская Краснодарского края уходила в
# нерелевантные вместе с работой МОГ. И наоборот: «Винницкое» и «Николаевка» —
# сёла Крыма, «Полтавская» — станица Кубани, «Новочеркасск» содержит
# «черкасс». Поэтому имена разделены на два списка, а решение принимается по
# совокупности признаков.

# Формы, которых российский тёзка не порождает: у села Киевское нет
# родительного «Киева», у хутора Харьковский — «Харькова», у Одесского района
# Омской области — «Одессы». Такое имя само называет чужой город.
#
# Косвенные падежи здесь обязательны: «кривой\s+рог» в именительном пропускал
# «прилёт по Эпицентру в Кривом Роге» и давал impact/9.
FOREIGN_CITY_RE = re.compile(
    r"\bкиев(?:а|е|у|ом)?\b|\bодесс(?:а|ы|е|у|ой)\b|\bхарьков(?:а|е|у|ом)?\b"
    r"|днепропетровск\w*|\bкрив(?:ой|ого|ому|ом|ым)\s+рог\w*|кривбасс\w*"
    r"|тегеран\w*|\bизраил(?:ь|я|ю|ем|е)\b|израильск\w*"
    r"|\bиран(?:а|у|е|ом)?\b|иранск\w*|ормузск\w+",
    re.IGNORECASE,
)

# Имена, у которых российские тёзки есть: Николаевка, Черниговка, станица
# Львовская, посёлок Черноморское, Херсонская и Запорожская области РФ.
# Само по себе такое слово не значит ничего — нужен второй признак.
FOREIGN_AMBIGUOUS_RE = re.compile(
    r"николаев\w*|чернигов\w*|львов\w*|черноморск\w*|херсон\w*|запорожь\w*"
    r"|киевск\w*|одесск\w*|харьковск\w*|каспийск\w+\s+мор\w+",
    re.IGNORECASE,
)

# Оборот, который прямо кладёт событие на украинскую землю. Слова «ВСУ» и
# «украинские БПЛА» в этот список не входят: ими описан и налёт на Ростов
# («Украинские БПЛА уничтожены над Орловской областью» — 43 таких сообщения),
# так что признаком чужой стороны они не являются.
FOREIGN_CONTEXT_RE = re.compile(
    r"контролируем\w+\s+(?:всу|украин\w*)|киевск\w+\s+режим|\bгсчс\b"
    r"|по\s+(?:территори|портам|объектам|городам|предприятиям)\w*\s+украин"
    r"|на\s+территории\s+украин|\bв\s+украине\b|вглубь\s+украин"
    r"|украинск\w+\s+(?:порт|полигон|город|территор|аэродром)"
    r"|порт\w*\s+[«\"']?(?:одесс|николаев|черноморск|измаил|южн)",
    re.IGNORECASE,
)

# Ленты новых регионов сами отделяют свою землю от чужой: «Херсонская область
# РФ», «Запорожская область РФ», «Николаевка, Береговое, Песчаное Республика
# Крым». Такая пометка рядом снимает подозрение с чужого имени: сообщение
# описывает нашу территорию, а чужой топоним в нём — точка старта или сосед.
#
# Вето сильное — оно перебивает даже однозначно чужой город, — поэтому в
# списке только явные пометки территории. «Кубань» отсюда убрана: это не
# пометка события, а самоназвание кубанских лент, и в футере «Оповещение
# Кубани» она снимала подозрение со сводок Минобороны об ударах по Одессе и
# Черноморску (5 сообщений корпуса). Футер такого вида strip_footer не режет,
# так что вето срабатывало на брендинге канала, а не на географии.
RUSSIAN_SIDE_RE = re.compile(
    r"област\w*\s+рф\b|\bлнр\b|\bднр\b|республик\w+\s+крым",
    re.IGNORECASE,
)

# --- Нерелевантное: сводка последствий --------------------------------------
# «Двое погибших, семеро ранены», «доставлен в областную больницу» — отчёт
# о вчерашнем налёте. Оповещение никогда не занимает 800 символов рассказа
# про больницы, а на карту такой текст положил бы событие задним числом.
AFTERMATH_RE = re.compile(
    r"госпитализир\w+|\bбольниц\w+|скор\w+\s+помощ|осколочн\w+\s+ранени"
    r"|получил\w*\s+ранени|пострадавш\w+\s+оказан|медицинск\w+\s+помощ"
    r"|выража\w+\s+(?:поддержк|соболезн)|склоняем\s+головы",
    re.IGNORECASE,
)

# --- Оговорка: канал сам не знает, что произошло ----------------------------
# «Новороссийск, уточняем характер взрыва» — это не сообщение о взрыве, а
# вопрос к самому себе; часом позже тот же куст лент написал, что по звукам
# всё штатно. Слово «взрыв» в такой фразе давало impact девятого уровня —
# высший на шкале, — и весь Краснодарский край окрашивался в красное.
#
# Ловится только прямая оговорка о самом событии. «По предварительной
# информации беспилотник атаковал автомобиль» под правило не попадает
# намеренно: там оговорка про подробности, а удар назван утвердительно.
UNCONFIRMED_RE = re.compile(
    r"уточня\w+\s+(?:характер|причин|информац|детал|что)"
    r"|проверя\w+\s+информац"
    r"|требует\w*\s+подтвержд"
    r"|характер\s+(?:взрыв|хлопк|звук)\w*\s+уточня",
    re.IGNORECASE,
)

# Во что превращается неподтверждённое «уже случилось». Событие не
# выдумано — канал что-то слышал, — но это ещё тревога, а не взрыв.
UNCONFIRMED_DOWNGRADE = {"impact": ("alarm", 7), "intercept": ("alarm", 7)}

# --- Нерелевантное: реклама канала ------------------------------------------
# «ВНИМАНИЕ! Идет массовая атака на регионы России. Просьба подписаться на
# канал и включить уведомления» — это объявление о самом канале, а не
# оповещение: места в нём нет, и на карту оно попадало по региону источника
# красной меткой над областью, под которой не выделено ни одного района.
#
# Обычную подпись в конце сообщения это не задевает: её снимает strip_footer,
# а здесь ловится призыв подписаться в самом теле.
PROMO_RE = re.compile(
    r"просьб\w*\s+подписа\w+|подпишитесь\s+на\s+канал|подписка\s+поможет"
    r"|включит[ье]\s+уведомлени|рекоменду\w+\s+подписа\w+"
    r"|подписаться\s*:?\s*https?://"
    r"|для\s+(?:оперативного\s+)?получения\s+\w+\s+оповещений",
    re.IGNORECASE,
)

# --- Нерелевантное: подсчёт последствий -------------------------------------
# «10 погибших и 100 раненых при ударе по выставке под Киевом», «6 человек
# погибли, 26 пострадали» — это репортаж о случившемся, а не оповещение:
# живая сводка не считает погибших, она предупреждает. Отдельно от
# AFTERMATH_RE, потому что тот срабатывает только на длинном тексте, а
# заголовок новости укладывается в две строки и проходил как фиксация.
CASUALTY_RE = re.compile(
    r"\d+\s+(?:погибш|человек\s+погиб|раненых|пострадав)"
    r"|погиб\w*\s+\d+|ранен\w*\s+\d+\s+человек",
    re.IGNORECASE,
)

# Пересказ чужого репортажа: «кадры с места», «СМИ пишут». Не зависит от
# уровня сигнала — это разговор о событии, а не сообщение о нём.
REPORTAGE_RE = re.compile(
    r"кадр\w*\s+с\s+места|\bсми\s+(?:пишут|сообщ\w+)|видео\s+с\s+места"
    r"|появились\s+кадры|как\s+сообщ\w+\s+\w*\s*сми",
    re.IGNORECASE,
)

# --- Нерелевантное: сводка задним числом ------------------------------------
# «За прошедшую ночь силами ПВО уничтожено 328 БПЛА над территориями
# Белгородской, Брянской, Воронежской...» — утренняя сводка Минобороны.
# Она описывает уже закончившуюся ночь, но приходит в 09:50 и разбиралась как
# работа ПВО прямо сейчас: одно сообщение раскладывалось в живое событие в
# каждом названном регионе. Хуже того, сводку дословно repost-ят два десятка
# лент, и каждая считалась отдельным подтверждением — так рождались события
# с 24 «независимыми» источниками и достоверностью 1.00.
#
# Признак строгий: живое оповещение никогда не описывает завершённый период.
# «Повышенное внимание по БПЛА этой ночью» — прогноз, а не сводка, и под
# правило не попадает намеренно.
RECAP_RE = re.compile(
    r"за\s+(?:прошедш|минувш|истекш)\w+\s+(?:ноч\w+|сутк\w+|день|дня)"
    r"|(?:прошедшей|минувшей)\s+ночью"
    r"|в\s+течение\s+(?:прошедш|минувш)\w+\s+(?:ночи|суток)"
    r"|итог\w+\s+(?:ноч|сут)\w+"
    # Сводка за отработавший интервал. Ночью её узнать было легко, а днём
    # она приходит в другой обёртке — «С 08:00 до 20:00 силами ПВО было
    # уничтожено 112 БПЛА над территориями Белгородской, Брянской...» — и
    # проходила как работа ПВО прямо сейчас. Хуже: все 112 целей ложились
    # на каждую названную область по отдельности, а «Ленинградская область»
    # из перечня садилась на Ленинградский район Краснодарского края.
    r"|над\s+территориями\s"
    # Та же сводка без интервала: «Перехвачены 182 БПЛА над регионами РФ».
    # Множественное число обязательно: «много БПЛА в небе над регионом» —
    # это живое сообщение, и терять его нельзя.
    r"|над\s+(?:\d+\s+)?регионами"
    r"|дежурны\w+\s+(?:средствами|силами)\s+пво"
    r"|с\s+\d{1,2}[.:]\d{2}\s+(?:мск\s+)?до\s+\d{1,2}[.:]\d{2}"
    r"|в\s+период\s+с\s+\d"
    r"|в\s+течени[еи]\s+(?:дня|суток)"
    r"|за\s+(?:сутки|весь\s+день|ночь)"
    r"|с\s+\d{1,2}\s+\w+\s+по\s+\d{1,2}\s+\w+",
    re.IGNORECASE,
)

# --- Нерелевантное: доклад «ничего не происходит» ---------------------------
# «Фиксаций над нашим воздушным пространством не наблюдаем», «по обстановке
# тихо» — канал сообщает, что событий НЕТ. Слова «фиксация» и «угроза» внутри
# такой фразы ловились как сигнал, и дежурный доклад о тишине уходил на карту
# наблюдением с severity 4-5. Гасим только когда тип угрозы не назван: в
# «в регионе тихо, над Тульской областью фиксации БПЛА» вторая половина —
# настоящее наблюдение, и терять её нельзя.
QUIET_RE = re.compile(
    r"фиксац\w*[^\n]{0,40}не\s+наблюда\w+|обстановк\w+\s+спокойн"
    r"|(?:по\s+обстановке|в\s+регионе|данный\s+момент)\s+тихо",
    re.IGNORECASE,
)

# --- Нерелевантное: памятки и методички -------------------------------------
# «Меры предосторожности при сбитии БПЛА», «Уровни тревог: какие бывают» —
# объясняют, как себя вести, а не что происходит сейчас.
GUIDE_RE = re.compile(
    r"уровни\s+тревог|что\s+означа\w+|\bпамятк\w+|правил\w+\s+поведени"
    r"|как\s+не\s+стать|отправить\s+всем\s+знаком|при\s+получении\s+сигнала",
    re.IGNORECASE,
)

# --- Сигнал: что произошло. Порядок важен, первое совпадение выигрывает -----
SIGNALS: list[tuple[str, str, int]] = [
    # Только именительный падеж: «отбоя ждём», «отбоя нет» — это ещё тревога.
    ("allclear",  r"\bотбой\b|угроза\s+мин\w*\s+нет"
                  r"|опасность\s+минова|отмен\w+\s+(?:угроз|опасност|тревог)", 0),
    # «Всё хорошо, салюты», «учения на пороховом заводе», «дезинформация» —
    # канал снимает собственную тревогу, событие на карту не идёт.
    # «Склад в Сарапуле НЕ БЫЛ АТАКОВАН, враг распространяет панику» — канал
    # опровергает слух. Без этого «атакован» из отрицания давало impact/9.
    ("retracted", r"погодн\w+\s+услови|без\s+паники|ложн\w+\s+(тревог|сработ)"
                  r"|дезинформац\w*|\bфейк\w*|не\s+подтвер\w+|вс[ёе]\s+хорошо"
                  r"|\bсалют[ыи]\b|\bучени[йяе]\w*|учебн\w+\s+стрельб"
                  r"|не\s+нес\w+\s+опасност|не\s+(?:был\w*\s+)?атакован\w*", 0),
    ("impact",    r"\bвзрыв\w*\b|\bприл[её]т\w*|\bгром\b|\bобстрел\w*", 9),
    ("intercept", r"\bсбити\w*|\bсбит\b|уничтожен\w*|работа\s+пво|\bпво\b", 8),
    # Новые каналы объявляют тревогу без слова «тревога»: «на подлёте»,
    # «готовность», «все в укрытие», «от окон».
    ("alarm",     r"\bтревог\w*|\bсирен\w*|угроз\w+\s+(непосредств|удара|атаки)"
                  r"|на\s+подл[её]те|\bготовность\b|приготов\w+\s+к"
                  r"|в\s+укрыти\w+|укройтесь|укрыти\w+\s+не\s+покида"
                  r"|\bот\s+окон\b|не\s+подходите\s+к\s+окнам"
                  # Только формы слова «пуск»: «пусковые» и «пускай» мимо.
                  r"|\bпуск(?:и|а|ов|ам|ами|ах)?\b|массов\w+\s+запуск", 7),
    ("danger",    r"\bопасност\w*|беспилотная\s+опасность", 5),
    # «Большая активность» без названного типа угрозы — это про что угодно
    # («большой активности Telegram не проявляет»), поэтому активность живёт
    # только в WEAK_SIGNALS, где рядом обязан стоять тип борта.
    # Фиксация весит как перехват, а не как предупреждение. «Опасность по
    # БПЛА» означает, что может прилететь; «фиксация» — что борт уже видят.
    # Второе конкретнее первого, и раньше они стояли на одном уровне: 711
    # фиксаций, 19% событий, красились тем же жёлтым, что и общая тревожность.
    ("detection", r"\bфиксац\w*|\bзафиксирован\w*|\bпрол[её]т\w*|\bзамечен"
                  r"|курс\w*\s+на\b|\bв\s+небе\b|\bнаблюда\w+\s+(?:борт|бпла|дрон)", 8),
    ("caution",   r"мер[ыу]\s+(безопасн|предостор)|\bвнимание\b|соблюда\w+\s+мер"
                  r"|будьте\s+остор\w+|сохраняйте\s+спокойстви"
                  r"|не\s+подходите\s+к\s+(?:осколк|обломк)"
                  r"|мчс\s+\w{0,14}\s*сообщ\w+", 3),
    ("infra",     r"аэропорт|крымск\w+\s+мост|движение\s+автотранспорт"
                  r"|ограничен\w+\s+на\s+ивп|\bивп\b|план\s+ков[её]р", 2),
    # Голое «угроза БЭК», «угроза по области» — тоже оповещение.
    ("danger",    r"\bугроз\w*", 5),
]

# --- Сигналы, которые сами по себе бытовые ----------------------------------
# «Пожар», «обломки», «атакован» без названного типа угрозы — это городская
# хроника («крупный пожар на улице Таращанцев») или новость про чужую войну.
# Засчитываем такой текст, только если рядом назван тип угрозы.
WEAK_SIGNALS: list[tuple[str, str, int]] = [
    ("impact",    r"обломк\w+|возгорани\w*|\bпожар\w*|задымлени\w*|детонац\w*"
                  r"|атакова\w+|\bударил\w*|поврежд\w+|попадани\w*", 9),
    # Тот же вес, что и у названной словом фиксации: «высокая активность
    # БПЛА», «в небе», «слышны звуки» — борт видят или слышат прямо сейчас.
    # Пока здесь стояла четвёрка, событие подписывалось «Фиксация» и
    # красилось жёлтым, как обычное предупреждение.
    ("detection", r"\bв\s+небе\b|слышн\w+\s+звук|\bактивност\w*"
                  r"|прош[лаиё]\w*\s+на\b|ид[её]т\s+в\s+сторону", 8),
]

# --- Тип угрозы -------------------------------------------------------------
THREATS: list[tuple[str, str]] = [
    ("fpv",      r"\bfpv\b|фпв\b|оптоволок\w*|на\s+волокне"),
    ("rocket",   r"\bракет\w*|баллистик\w*|\bкалибр\b|искандер|фламинго|flamingo"
                 r"|\bшторм\s?шедоу|нептун|хаймарс|himars"),
    ("kab",      r"\bкаб\b|\bуаб\b|управляем\w+\s+авиабомб|планирующ\w+\s+бомб"),
    ("bek",      r"\bбэк\b|безэкипаж\w*|морск\w+\s+дрон"),
    ("aviation", r"авиац\w*|\bмиг-\d|\bту-\d|\bсу-\d|тактическ\w+\s+авиац"),
    # Новые каналы называют борт по типу: «Дартс», «Хорнет», «Молния», «Лютый».
    ("uav",      r"\bбпла\b|беспилот\w*|\bдрон\w*|\bгерань|\bшахед"
                 r"|\bдарт[сц]\w*|\bдарст\w*|\bхорнет\w*|\bлютый\w*|\bмолни[яию]\b"),
]

DIRECTIONS = {
    "север": 0, "северо-восток": 45, "восток": 90, "юго-восток": 135,
    "юг": 180, "юго-запад": 225, "запад": 270, "северо-запад": 315,
}
DIRECTION_FROM_RE = re.compile(
    r"\bс\s+(север[о\-]?восток\w*|юг[о\-]?восток\w*|север[о\-]?запад\w*|юг[о\-]?запад\w*"
    r"|север\w*|юг\w*|восток\w*|запад\w*)", re.IGNORECASE)
DIRECTION_TO_RE = re.compile(r"в\s+(?:направлении|сторону)\s+([А-ЯЁ][\w\-]+)", re.IGNORECASE)

# Движение цели без указания места назначения: «БПЛА противника на север»,
# «прошли на Армавир», «ударный БПЛА в направлении».
MOVEMENT_RE = re.compile(
    r"\bна\s+(?:север|юг|восток|запад)\w*|курс\w*\s+на\b|в\s+сторону"
    r"|в\s+направлени\w*|прош[лаиё]\w*\s+на\b|\bлет[ия]т|\bв\s+тыл\b"
    r"|\bот\s+гг\b|\bс\s+моря\b", re.IGNORECASE)

# Оглядка назад отсекает хвост длинного числа с пробелом-разделителем:
# в «численность 2 426 130 единиц» иначе вычитывалось 130 целей, и severity
# росла из-за порога «5 и больше».
COUNT_RE = re.compile(
    r"(?<!\d\s)\b(?:ещ[её]\s+)?(?:от\s+)?(\d{1,3})\s*(?:х\s*)?"
    r"(?:бпла|дрон\w*|цел\w*|борт\w*|фпв|каб|уаб|ракет\w*"
    r"|штук\w*|шт\b|единиц(?!\w*\s+техник)\w*)",
    re.IGNORECASE)
MANY_RE = re.compile(
    r"мног\w+\s+фиксац|групп\w+\s+бпла|масс\w+\s+(?:прол[её]т|запуск|пуск|атак)",
    re.IGNORECASE)

# Официальная врезка РСЧС — отдельный класс с высоким доверием.
RSCHS_RE = re.compile(r"рсчс|экстренн\w+\s+информац|беспилотная\s+опасность\s+на\s+территории", re.IGNORECASE)

SPLIT_LINE_RE = re.compile(r"[\n;]+")

# Оповещение — короткая реплика. Телеграфный формат новых региональных лент
# («Брянск, новостройка БПЛА», «Суземка фпв на оптоволокне по жд») вообще
# обходится без глагола, поэтому одного названного типа угрозы в короткой
# строке достаточно, чтобы счесть сообщение оповещением.
TELEGRAPH_LIMIT = 200

# Длинный текст в этих лентах — новость, реклама или памятка. «Сбитие»,
# «пожар» и «прилёт» в нём пересказ, а не наблюдение.
ARTICLE_LIMIT = 320

# Предел куска, в котором geocode ищет топоним. Порог не про длину названия, а
# про цену ошибки: чем длиннее кусок, тем больше в нём посторонних слов и тем
# выше шанс, что стеммер найдёт им тёзку в справочнике.
#
# Замерено на всём корпусе (4041 сообщение) по доле мусора среди зон, которые
# добавляет расширение полосы. 90->120 даёт +188 зон, ошибочных из них 4 (2%):
# почти всё это головной элемент перечисления, терявшийся вместе с преамбулой
# («…уничтожено 133 БПЛА над территориями Белгородской, Брянской…»,
# «…муниципальных образований: Темрюкский, Крымский…»), и целые оповещения
# вида «Воздушная тревога в связи с угрозой непосредственного удара БПЛА по
# Лискинскому району». Следующая полоса 120->130 даёт всего +18 зон, а ошибок
# в ней уже 4 (22%), 130->160 — +7 зон и 2 ошибки. То есть за 120 начинает
# расти шум, а не покрытие, и граница проходит здесь.
PHRASE_MAX_LEN = 120

# Контексты, в которых новостная лексика перевешивает слабый сигнал.
WEAK_CONTEXT = {"unknown", "caution", "infra"}
RETRO_CONTEXT = WEAK_CONTEXT | {"impact", "intercept"}
# Классы, в которых сводка задним числом выглядит как наблюдение. Отбой и
# объявленная тревога сюда не входят: они говорят про сейчас, даже если рядом
# упомянута прошедшая ночь.
RECAP_CONTEXT = RETRO_CONTEXT | {"detection"}
# Классы, которые мог породить один лишь дежурный доклад о тишине.
QUIET_CONTEXT = WEAK_CONTEXT | {"danger", "detection"}
# Классы, до которых дотягивается оборонная новость. Дальше не пускаем:
# «отбой», «тревога» и «работа ПВО» — слова наблюдения, и рядом с ними
# «ВКС РФ» или «праздник ВМФ» остаются просто деталью оповещения.
MILITARY_CONTEXT = WEAK_CONTEXT | {"danger", "detection"}


@dataclass
class Observation:
    """Одно наблюдение, извлеченное из одного сообщения."""

    signal_type: str = "unknown"
    threat_type: str = "unknown"
    severity: int = 1
    place_phrases: list[str] = field(default_factory=list)
    direction_deg: int | None = None
    target_count: int | None = None
    official: bool = False
    relevant: bool = True
    body: str = ""


def strip_footer(text: str) -> str:
    kept: list[str] = []
    for line in text.split("\n"):
        if FOOTER_RE.search(line):
            continue
        if len(line.strip()) <= FOOTER_MAX_LEN and FOOTER_BRAND_RE.search(line):
            continue
        kept.append(line)
    return "\n".join(kept).strip()


def foreign_side(text: str) -> bool:
    """Сообщение рассказывает о чужой стороне, а не о нашей обстановке.

    Чужая сторона опознаётся совокупностью признаков, а не одним словом.
    Однозначно чужого имени («в Кривом Роге», «под Киевом») хватает самого по
    себе; неоднозначному («в Николаеве», «в Херсоне») нужен оборот, кладущий
    событие на украинскую землю. И то и другое отменяется, если рядом стоит
    российская привязка: тогда чужой топоним — точка старта или сосед, а
    сообщение всё равно про нашу территорию.
    """
    if RUSSIAN_SIDE_RE.search(text):
        return False
    if FOREIGN_CITY_RE.search(text):
        return True
    return bool(FOREIGN_AMBIGUOUS_RE.search(text) and FOREIGN_CONTEXT_RE.search(text))


def classify_signal(text: str, threat: str = "unknown") -> tuple[str, int]:
    for name, pattern, severity in SIGNALS:
        if re.search(pattern, text, re.IGNORECASE):
            return name, severity
    if threat != "unknown":
        for name, pattern, severity in WEAK_SIGNALS:
            if re.search(pattern, text, re.IGNORECASE):
                return name, severity
    return "unknown", 1


def classify_threat(text: str) -> str:
    for name, pattern in THREATS:
        if re.search(pattern, text, re.IGNORECASE):
            return name
    return "unknown"


def extract_direction(text: str) -> int | None:
    match = DIRECTION_FROM_RE.search(text)
    if not match:
        return None
    token = norm_key(match.group(1))
    for name, degrees in DIRECTIONS.items():
        if token.startswith(name.replace("-", "")[:6]) or token.startswith(name[:6]):
            return degrees
    return None


def extract_count(text: str) -> int | None:
    numbers = [int(value) for value in COUNT_RE.findall(text) if 0 < int(value) <= 200]
    if numbers:
        return max(numbers)
    return 10 if MANY_RE.search(text) else None


def candidate_phrases(body: str) -> list[str]:
    """Фрагменты, в которых geocode ищет топонимы.

    Телеграфный формат кладет места на отдельные строки, Локатор и РВК —
    через запятую в одной строке. Официальные ленты пишут одним длинным
    предложением с двоеточием: «Курская область: авиационная опасность».
    Режем по строкам, запятым, двоеточиям и точкам.
    """
    phrases: list[str] = []
    for line in SPLIT_LINE_RE.split(body):
        line = line.strip(" .!?—-•")
        if not line:
            continue
        for chunk in re.split(r"[,;:·]|(?<=[а-яё])\.\s+| - | — ", line):
            if chunk is None:
                continue
            chunk = chunk.strip(" .!?—-•\u200b")
            if len(chunk) < 3:
                continue
            # Порог сохранён: в куске длиннее него посторонних слов больше,
            # чем пользы. Официальный формат чинится не отменой порога, а
            # добавленным разбиением по двоеточию и точке — «Курская область:
            # авиационная опасность» распадается на короткие куски сама.
            if len(chunk) > PHRASE_MAX_LEN:
                continue
            phrases.append(chunk)
    return phrases


# Полосы цвета на карте: ниже 4 — служебное, 4-5 опасность, 6-7 тревога,
# 8 и выше — борт уже видят. Подпись события берётся из типа сигнала, а
# заливка из уровня, и расходиться они не должны.
SEVERITY_BANDS = ((4, 3), (6, 5), (8, 7))


def band_ceiling(severity: int) -> int:
    """Потолок полосы, в которой лежит уровень."""
    for edge, ceiling in SEVERITY_BANDS:
        if severity < edge:
            return ceiling
    return 10


def parse(text: str) -> Observation:
    body = strip_footer(text)
    observation = Observation(body=body)

    if not body:
        observation.relevant = False
        return observation

    observation.official = bool(RSCHS_RE.search(body))

    # Классифицируем по тексту без инструкций: «до сигнала Отбой» не отбой.
    clean = INSTRUCTION_RE.sub(" ", body)

    threat = classify_threat(clean)
    signal, severity = classify_signal(clean, threat)

    # «Ещё 2 БПЛА от Новобелая в сторону Воронежа» — глагола нет, но это
    # фиксация: назван тип угрозы вместе с движением или счётом целей.
    # Борт уже видят и ведут, и весит это столько же, сколько названная
    # словом «фиксация»: раньше запасной разбор ставил 4, и на карте
    # «Фиксация» подписывалась красным словом, а красилась жёлтым —
    # 142 события из 717.
    #
    # Счёт целей заменяет тип угрозы: «От 2х единиц прошли на Армавир» —
    # «единицы», «борта», «цели» в этих лентах и есть беспилотники.
    if signal == "unknown" and (threat != "unknown" or COUNT_RE.search(clean)) and (
        DIRECTION_FROM_RE.search(clean)
        or DIRECTION_TO_RE.search(clean)
        or MOVEMENT_RE.search(clean)
        or COUNT_RE.search(clean)
        or MANY_RE.search(clean)
        or len(clean) <= TELEGRAPH_LIMIT
    ):
        signal, severity = "detection", 8

    # Канал сам не знает, что произошло: это ещё тревога, а не факт.
    if signal in UNCONFIRMED_DOWNGRADE and UNCONFIRMED_RE.search(clean):
        signal, severity = UNCONFIRMED_DOWNGRADE[signal]
    # Реклама канала: сообщение о себе, а не об обстановке.
    if PROMO_RE.search(clean):
        observation.relevant = False
        return observation
    # Памятка объясняет, как себя вести, а не что происходит.
    if GUIDE_RE.search(clean):
        observation.relevant = False
        return observation
    # Подсчёт последствий и пересказ чужого репортажа: событие описано, а не
    # объявлено. Объявленную тревогу это не задевает — она про сейчас.
    if signal not in ("alarm", "allclear") and (
        CASUALTY_RE.search(clean) or REPORTAGE_RE.search(clean)
    ):
        observation.relevant = False
        return observation
    # Сводка за уже прошедший период: событие в ней закончилось до публикации.
    if RECAP_RE.search(clean) and signal in RECAP_CONTEXT:
        observation.relevant = False
        return observation
    # Дежурный доклад о тишине: события нет, класть на карту нечего.
    if threat == "unknown" and signal in QUIET_CONTEXT and QUIET_RE.search(clean):
        observation.relevant = False
        return observation
    # Новость про вооружение и намерения: тип угрозы назван, наблюдения нет.
    if MILITARY_NEWS_RE.search(clean) and signal in MILITARY_CONTEXT:
        observation.relevant = False
        return observation
    # Пересказ чужой войны: сильный сигнал там относится не к нашей карте.
    foreign = foreign_side(clean)
    if foreign and signal in RETRO_CONTEXT:
        observation.relevant = False
        return observation
    # Новостной текст без признаков обстановки — не наше событие.
    if NEWS_RE.search(clean) and signal in WEAK_CONTEXT:
        observation.relevant = False
        return observation
    # Статья с новостными маркерами или сводка последствий: сигнал в ней
    # пересказан, а не наблюдён. Объявленная тревога — исключение: канал
    # предупреждает о пусках подробно, называя чужой регион как точку старта
    # («Враг готовит массированные пуски от Харьковской области в сторону
    # Белгородской»), и такое оповещение терять нельзя.
    if signal != "alarm" and len(clean) > ARTICLE_LIMIT and (
        NEWS_RE.search(clean) or foreign or AFTERMATH_RE.search(clean)
    ):
        observation.relevant = False
        return observation
    if signal == "unknown":
        observation.relevant = False
        return observation
    # «Меры безопасности», «внимание по БПЛА», «не подходите к обломкам» —
    # призыв к бдительности, а не событие: решением владельца проекта класс
    # на карту не идёт вовсе. Сам паттерн из SIGNALS при этом не удалён
    # намеренно: без него «не подходите к обломкам БПЛА» переползало бы
    # через WEAK_SIGNALS в impact и красило район взрывом.
    if signal == "caution":
        observation.relevant = False
        return observation

    observation.signal_type = signal
    observation.severity = severity
    observation.threat_type = threat
    observation.direction_deg = extract_direction(clean)
    observation.target_count = extract_count(clean)
    observation.place_phrases = candidate_phrases(body)

    # Официальные врезки и групповые налеты весомее — но в пределах своей
    # полосы. Надбавка добавляет веса при сортировке, а не меняет цвет:
    # без потолка «Тревога» от МЧС уходила в красную полосу, а «Опасность»
    # с полусотней целей — в оранжевую, и подпись расходилась с заливкой.
    ceiling = band_ceiling(severity)
    if observation.official:
        observation.severity = min(ceiling, observation.severity + 1)
    if observation.target_count and observation.target_count >= 5:
        observation.severity = min(ceiling, observation.severity + 1)

    return observation
