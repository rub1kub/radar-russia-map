DIRECTION_FROM_RE = re.compile(
    r"\bс\s+(север[о\-]?восток\w*|юг[о\-]?восток\w*|север[о\-]?запад\w*|юг[о\-]?запад\w*"
    r"|север\w*|юг\w*|восток\w*|запад\w*)", re.IGNORECASE)
DIRECTION_TO_RE = re.compile(r"в\s+(?:направлении|сторону)\s+([А-ЯЁ][\w\-]+)", re.IGNORECASE)

# Движение цели без указания места назначения: «БПЛА противника на север»,
# «прошли на Армавир», «ударный БПЛА в направлении».
MOVEMENT_RE = re.compile(
    r"\bна\s+(?:север|юг|восток|запад)\w*|курс(?:ом)?\s+на\b|в\s+сторону"
    r"|в\s+направлени\w*|прош[лаиё]\w*\s+на\b|\bлет[ия]т|\bв\s+тыл\b"
    r"|\bот\s+гг\b|\bс\s+моря\b", re.IGNORECASE)

# Оглядка назад отсекает хвост длинного числа с пробелом-разделителем:
# в «численность 2 426 130 единиц» иначе вычитывалось 130 целей, и severity
# росла из-за порога «5 и больше».
COUNT_RE = re.compile(
    r"(?<!\d\s)\b(?:ещ[её]\s+)?(?:от\s+)?(\d{1,3})\s*(?:х\s*)?"
    r"(?:бпла|дрон\w*|цел\w*|борт\w*|фпв|каб|уаб|ракет\w*"
    r"|штук\w*|шт\b|единиц(?!\w*\s+техник)\w*)",
    re.IGNORECASE)
MANY_RE = re.compile(
    r"мног\w+\s+фиксац|групп\w+\s+бпла|масс\w+\s+(?:прол[её]т|запуск|пуск|атак)",
    re.IGNORECASE)

# Официальная врезка РСЧС — отдельный класс с высоким доверием.
RSCHS_RE = re.compile(r"рсчс|экстренн\w+\s+информац|беспилотная\s+опасность\s+на\s+территории", re.IGNORECASE)

SPLIT_LINE_RE = re.compile(r"[\n;]+")

# Оповещение — короткая реплика. Телеграфный формат новых региональных лент
# («Брянск, новостройка БПЛА», «Суземка фпв на оптоволокне по жд») вообще
# обходится без глагола, поэтому одного названного типа угрозы в короткой
# строке достаточно, чтобы счесть сообщение оповещением.
TELEGRAPH_LIMIT = 200

# Длинный текст в этих лентах — новость, реклама или памятка. «Сбитие»,
# «пожар» и «прилёт» в нём пересказ, а не наблюдение.
ARTICLE_LIMIT = 320

# Предел куска, в котором geocode ищет топоним. Порог не про длину названия, а
# про цену ошибки: чем длиннее кусок, тем больше в нём посторонних слов и тем
# выше шанс, что стеммер найдёт им тёзку в справочнике.
#
# Замерено на всём корпусе (4041 сообщение) по доле мусора среди зон, которые
# добавляет расширение полосы. 90->120 даёт +188 зон, ошибочных из них 4 (2%):
# почти всё это головной элемент перечисления, терявшийся вместе с преамбулой
# («…уничтожено 133 БПЛА над территориями Белгородской, Брянской…»,
# «…муниципальных образований: Темрюкский, Крымский…»), и целые оповещения
# вида «Воздушная тревога в связи с угрозой непосредственного удара БПЛА по
# Лискинскому району». Следующая полоса 120->130 даёт всего +18 зон, а ошибок
# в ней уже 4 (22%), 130->160 — +7 зон и 2 ошибки. То есть за 120 начинает
# расти шум, а не покрытие, и граница проходит здесь.
PHRASE_MAX_LEN = 120

# Контексты, в которых новостная лексика перевешивает слабый сигнал.
WEAK_CONTEXT = {"unknown", "caution", "infra"}
RETRO_CONTEXT = WEAK_CONTEXT | {"impact", "intercept"}
# Классы, в которых сводка задним числом выглядит как наблюдение. Отбой и
# объявленная тревога сюда не входят: они говорят про сейчас, даже если рядом
# упомянута прошедшая ночь.
RECAP_CONTEXT = RETRO_CONTEXT | {"detection"}
# Классы, которые мог породить один лишь дежурный доклад о тишине.
QUIET_CONTEXT = WEAK_CONTEXT | {"danger", "detection", "intercept"}
# Классы, до которых дотягивается оборонная новость. Дальше не пускаем:
# «отбой», «тревога» и «работа ПВО» — слова наблюдения, и рядом с ними
# «ВКС РФ» или «праздник ВМФ» остаются просто деталью оповещения.
MILITARY_CONTEXT = WEAK_CONTEXT | {"danger", "detection"}


@dataclass
class Observation:
    """Одно наблюдение, извлеченное из одного сообщения."""

    signal_type: str = "unknown"
    threat_type: str = "unknown"
    severity: int = 1
    place_phrases: list[str] = field(default_factory=list)
    direction_deg: int | None = None
    target_count: int | None = None
    # Источник назвал налёт групповым, не назвав числа бортов.
    massive: bool = False
    official: bool = False
    relevant: bool = True
    body: str = ""


def strip_footer(text: str) -> str:
    kept: list[str] = []
    for line in text.split("\n"):
        if FOOTER_RE.search(line):
            continue
        if len(line.strip()) <= FOOTER_MAX_LEN and FOOTER_BRAND_RE.search(line):
            continue
        kept.append(line)
    return "\n".join(kept).strip()


def foreign_side(text: str) -> bool:
    """Сообщение рассказывает о чужой стороне, а не о нашей обстановке.

    Чужая сторона опознаётся совокупностью признаков, а не одним словом.
    Однозначно чужого имени («в Кривом Роге», «под Киевом») хватает самого по
    себе; неоднозначному («в Николаеве», «в Херсоне») нужен оборот, кладущий
    событие на украинскую землю. И то и другое отменяется, если рядом стоит
    российская привязка: тогда чужой топоним — точка старта или сосед, а
    сообщение всё равно про нашу территорию.
    """
    if RUSSIAN_SIDE_RE.search(text):
        return False
    if FOREIGN_CITY_RE.search(text):
        return True
    return bool(FOREIGN_AMBIGUOUS_RE.search(text) and FOREIGN_CONTEXT_RE.search(text))


def classify_signal(text: str, threat: str = "unknown") -> tuple[str, int]:
    for name, pattern, severity in SIGNALS:
        if re.search(pattern, text, re.IGNORECASE):
            return name, severity
    if threat != "unknown":
        for name, pattern, severity in WEAK_SIGNALS:
            if re.search(pattern, text, re.IGNORECASE):
                return name, severity
    return "unknown", 1


def classify_threat(text: str) -> str:
    for name, pattern in THREATS:
        if re.search(pattern, text, re.IGNORECASE):
            return name
    return "unknown"


def extract_direction(text: str) -> int | None:
    match = DIRECTION_FROM_RE.search(text)
    if not match:
        return None
    token = norm_key(match.group(1))
    for name, degrees in DIRECTIONS.items():
        if token.startswith(name.replace("-", "")[:6]) or token.startswith(name[:6]):
            return degrees
    return None


def extract_count(text: str) -> int | None:
    """Число целей — только если оно названо в тексте.

    Раньше «массированный налёт» превращался в ровно 10 целей, и карточка
    писала «10 целей» там, где источник не называл ни одной: цифра была
    нашей выдумкой, выданной за факт. Массированность теперь живёт
    отдельным признаком — см. is_massive().
    """
    numbers = [int(value) for value in COUNT_RE.findall(text) if 0 < int(value) <= 200]
    return max(numbers) if numbers else None


def is_massive(text: str) -> bool:
    """Источник говорит о группе бортов, не называя их числа."""
    return bool(MANY_RE.search(text))


# Служебные поля шаблонных лент. «⚡ Уровень: Высокий» — это степень угрозы,
# а не место, но разбиение по двоеточию оставляло от неё одинокое «Высокий»,
# и оно садилось на посёлок Высокий: 207 событий в Оленегорске Мурманской
# области, ещё под две сотни в Краснодарском крае, Ростовской, Воронежской и
# Орловской. Из трёхсот сообщений с этим словом 299 — именно такое поле.
#
# Соседнее поле «📍 Регион: Московская область» не трогаем: там место
# настоящее и единственное на всё сообщение.
LEVEL_FIELD_RE = re.compile(
    r"^[^\wа-яё]*уровень\s*:.*$",
    re.IGNORECASE | re.MULTILINE,
)


def candidate_phrases(body: str) -> list[str]:
    """Фрагменты, в которых geocode ищет топонимы.

    Телеграфный формат кладет места на отдельные строки, Локатор и РВК —
    через запятую в одной строке. Официальные ленты пишут одним длинным
    предложением с двоеточием: «Курская область: авиационная опасность».
    Режем по строкам, запятым, двоеточиям и точкам.
    """
    phrases: list[str] = []
    body = LEVEL_FIELD_RE.sub(" ", body)
    for line in SPLIT_LINE_RE.split(body):
        line = line.strip(" .!?—-•")
        if not line:
            continue
        for chunk in re.split(r"[,;:·]|(?<=[а-яё])\.\s+| - | — ", line):
            if chunk is None:
                continue
            chunk = chunk.strip(" .!?—-•\u200b")
            if len(chunk) < 3:
                continue
            # Порог сохранён: в куске длиннее него посторонних слов больше,
            # чем пользы. Официальный формат чинится не отменой порога, а
            # добавленным разбиением по двоеточию и точке — «Курская область:
            # авиационная опасность» распадается на короткие куски сама.
            if len(chunk) > PHRASE_MAX_LEN:
                continue
            phrases.append(chunk)
    return phrases


# Полосы цвета на карте: ниже 4 — служебное, 4-5 опасность, 6-7 тревога,
# 8 и выше — борт уже видят. Подпись события берётся из типа сигнала, а
# заливка из уровня, и расходиться они не должны.
SEVERITY_BANDS = ((4, 3), (6, 5), (8, 7))


def band_ceiling(severity: int) -> int:
    """Потолок полосы, в которой лежит уровень."""
    for edge, ceiling in SEVERITY_BANDS:
        if severity < edge:
            return ceiling
    return 10


def parse(text: str) -> Observation:
    body = strip_footer(text)
    observation = Observation(body=body)

    if not body:
        observation.relevant = False
        return observation

    observation.official = bool(RSCHS_RE.search(body))

    # Классифицируем по тексту без инструкций: «до сигнала Отбой» не отбой,
    # запрет съёмки — не работа ПВО.
    clean = FILMING_BAN_RE.sub(" ", INSTRUCTION_RE.sub(" ", body))

    threat = classify_threat(clean)
    signal, severity = classify_signal(clean, threat)

    # Аэропорты и прочая инфраструктура живут парой «закрыто — открыто»
    # со своим типом угрозы: у закрытия собственный отбой («СНЯТЫ
    # ограничения»), и он не должен гасить дроновую тревогу в том же
    # городе, как и «отбой БПЛА» не открывает аэропорт. Тип угрозы
    # затирается, только если текст сам не назвал угрозу: «Аэропорт X.
    # ВВЕДЕНЫ ограничения» не говорит, из-за чего. А «повышенная
    # бдительность по БПЛА, введены ограничения в аэропорту» — называет:
    # затирать «uav» здесь нельзя, иначе следом идущая «ВОЗДУШНАЯ ТРЕВОГА»
    # (сама без слова «БПЛА») наследует «infra» и теряет тип угрозы.
    if signal == "infra":
        if INFRA_OPEN_RE.search(clean):
            signal, severity = "allclear", 0
        if threat == "unknown":
            threat = "airport" if AIR_INFRA_RE.search(clean) else "infra"

    # «Ещё 2 БПЛА от Новобелая в сторону Воронежа» — глагола нет, но это
    # фиксация: назван тип угрозы вместе с движением или счётом целей.
    # Борт уже видят и ведут, и весит это столько же, сколько названная
    # словом «фиксация»: раньше запасной разбор ставил 4, и на карте
    # «Фиксация» подписывалась красным словом, а красилась жёлтым —
    # 142 события из 717.
    #
    # Счёт целей заменяет тип угрозы: «От 2х единиц прошли на Армавир» —
    # «единицы», «борта», «цели» в этих лентах и есть беспилотники.
    # Телеграфный запасной разбор не работает для текстов с третьими
    # странами: «Турция закрывает проход судов из-за атак БПЛА» — новость,
    # а фолбэк делал из неё фиксацию восьмого уровня. Украинские города
    # сюда не входят: «от Днепропетровской области много БПЛА в сторону
    # ЛНР» — живое предупреждение, и точка старта у него чужая всегда.
    if signal == "unknown" and (threat != "unknown" or COUNT_RE.search(clean)) and (
            not THIRD_COUNTRY_RE.search(clean)) and (
        DIRECTION_FROM_RE.search(clean)
        or DIRECTION_TO_RE.search(clean)
        or MOVEMENT_RE.search(clean)
        or COUNT_RE.search(clean)
        or MANY_RE.search(clean)
        or len(clean) <= TELEGRAPH_LIMIT
    ):
        # Движение к зоне — предупреждение для неё, а не наблюдение в ней.
        if MOVING_TO_RE.search(clean):
            signal, severity = "danger", 5
        else:
            signal, severity = "detection", 8

    # Совет укрыться при живой фиксации — фиксация, а не тревога. Снимаем
    # советы и смотрим остаток: если тревога держалась только на них, а в
    # тексте видят борт, событие — «здесь видят борт».
    if signal == "alarm" and ALARM_ADVICE_RE.search(clean):
        rest_signal, rest_severity = classify_signal(
            ALARM_ADVICE_RE.sub(" ", clean), threat)
        if rest_signal == "detection":
            signal, severity = rest_signal, rest_severity

    # Канал сам не знает, что произошло: это ещё тревога, а не факт.
    if signal in UNCONFIRMED_DOWNGRADE and UNCONFIRMED_RE.search(clean):
        signal, severity = UNCONFIRMED_DOWNGRADE[signal]
    # Ожидание фиксаций — предупреждение, а не наблюдение. Понижаем только
    # когда после удаления оборотов ожидания признаков фиксации не остаётся:
    # «фиксация над Ейском, внимание по фиксациям соседям» — настоящая.
    if (signal == "detection" and ANTICIPATION_RE.search(clean)
            and not DETECTION_RE.search(ANTICIPATION_RE.sub(" ", clean))):
        signal, severity = "danger", 5
    # «К вам», «на вас», «в вашу сторону» — борт идёт сюда, а видят его
    # где-то ещё. Названное место — адресат предупреждения, и красить его
    # как «здесь видят борт» нельзя. Проверки на остаток нет намеренно:
    # см. APPROACH_RE.
    if signal == "detection" and APPROACH_RE.search(clean):
        signal, severity = "danger", 5
    # То же и с перехватом: «Приготовиться к сбитиям» — это тревога, борт
    # ещё летит. Понижаем до тревоги, а не до опасности: «приготовиться»
    # говорят, когда прилёта ждут вот-вот.
    if (signal == "intercept" and ANTICIPATION_RE.search(clean)
            and not INTERCEPT_RE.search(ANTICIPATION_RE.sub(" ", clean))):
        signal, severity = "alarm", 7
    # «Будет работать ПВО» — обещание, а не работа: если кроме будущего
    # времени перехвата в тексте нет, это предупреждение.
    if (signal == "intercept" and FUTURE_WORK_RE.search(clean)
            and not INTERCEPT_RE.search(FUTURE_WORK_RE.sub(" ", clean))):
        signal, severity = "alarm", 7
    # «С тревогой ждёт сентября» — оборот речи, а не объявленная тревога.
    # Сленговая «тревога» теперь классифицируется опасностью, поэтому
    # идиому ловим в обоих классах.
    if signal in ("alarm", "danger") and ANXIETY_IDIOM_RE.search(clean):
        rest = ANXIETY_IDIOM_RE.sub(" ", clean)
        signal, severity = classify_signal(rest, observation.threat_type)
    # Подготовка укрытий «на случай» — не действующая опасность. Убираем
    # обороты подготовки; сигнал в остатке ищется заново: «опасность БПЛА,
    # укройтесь в подвалах» рядом с настоящим оповещением выживает.
    # «На случай атак БПЛА» умеет прикинуться и фиксацией, и ударом —
    # поэтому перепроверяются все четыре класса.
    if (signal in ("alarm", "danger", "detection", "impact")
            and PREPARATION_RE.search(clean)):
        rest = PREPARATION_RE.sub(" ", clean)
        signal, severity = classify_signal(rest, observation.threat_type)
    # И с ударом: «готовность к возможному обстрелу» — обстрела ещё не
    # было. «Погар и близлежащие готовность к возможному обстрелу» рисовало
    # прилёт девятого уровня по посёлку, который только предупредили.
    if (signal == "impact" and ANTICIPATION_RE.search(clean)
            and not IMPACT_RE.search(ANTICIPATION_RE.sub(" ", clean))):
        signal, severity = "alarm", 7
    # Условие вместо события: «меры безопасности при сбитиях БПЛА». Снимаем
    # оборот и смотрим, остаётся ли перехват в остатке — «сбит над Анапой,
    # при сбитиях не подходите к окнам» настоящий и должен уцелеть. Если не
    # остаётся, сигнал ищется заново по тексту без условия: сообщение почти
    # всегда всё равно про тревогу, и терять её нельзя.
    if signal == "intercept" and CONDITIONAL_INTERCEPT_RE.search(clean):
        rest = CONDITIONAL_INTERCEPT_RE.sub(" ", clean)
        if not INTERCEPT_RE.search(rest):
            signal, severity = classify_signal(rest, observation.threat_type)
    # Обломки после факта — не событие в эфире: борт упал когда-то раньше.
    # Две формы хроники: находка («обнаружили обломки») и падение с явным
    # «последствий нет». Убираем, только если кроме хроники признаков
    # удара не остаётся: «обнаружены обломки, повреждена крыша» и
    # «обломки упали, пострадали четверо» — настоящие удары.
    if signal in ("impact", "detection"):
        aftermath = DEBRIS_FOUND_RE.search(clean) or (
            DEBRIS_FALL_RE.search(clean) and NO_HARM_RE.search(clean))
        rest = DEBRIS_NOUN_RE.sub(" ", clean)
        if (aftermath and not IMPACT_RE.search(rest)
                and not WEAK_IMPACT_RE.search(rest)):
            observation.relevant = False
            return observation
    # Реклама канала: сообщение о себе, а не об обстановке.
    if PROMO_RE.search(clean):
        observation.relevant = False
        return observation
    # Объявление канала о себе: обстановки в нём нет ни при каком сигнале.
    if CHANNEL_NOTICE_RE.search(clean):
        observation.relevant = False
        return observation
    # Благодарность расчётам — про налёт, который уже отбит.
    if GRATITUDE_RE.search(clean):
        observation.relevant = False
        return observation
    # Перепалка каналов: спор о том, было ли сбитие, — не сбитие.
    if POLEMIC_RE.search(clean):
        observation.relevant = False
        return observation
    # Работа по наземной цели: пункт управления, склад, стартовая позиция.
    if GROUND_TARGET_RE.search(clean):
        observation.relevant = False
        return observation
    # Анонс своих плановых стрельб — не налёт.
    if DRILL_RE.search(clean):
        observation.relevant = False
        return observation
    # Пейнтбол и пневматика — городская хроника, не обстрел.
    if CIVILIAN_WEAPON_RE.search(clean):
        observation.relevant = False
        return observation
    # Список радиостанций — это справка, а не обстановка.
    if RADIO_GUIDE_RE.search(clean):
        observation.relevant = False
        return observation
    # Памятка объясняет, как себя вести, а не что происходит.
    if GUIDE_RE.search(clean):
        observation.relevant = False
        return observation
    # Опрос читателей: весь сигнал стоит внутри вопроса. Снимаем вопросы и
    # смотрим, остаётся ли утверждение — «Долгоруково, сообщают о пролётах
    # БПЛА. Вы слышали?» остаётся, «Краснодар слышали взрывы?» нет.
    if "?" in clean:
        statements = drop_questions(clean)
        if classify_signal(statements, observation.threat_type)[0] == "unknown":
            observation.relevant = False
            return observation
    # Подсчёт последствий и пересказ чужого репортажа: событие описано, а не
    # объявлено. Объявленную тревогу это не задевает — она про сейчас.
    if signal not in ("alarm", "allclear") and (
        CASUALTY_RE.search(clean) or REPORTAGE_RE.search(clean)
    ):
        observation.relevant = False
        return observation
    # Газетная аналитика со ссылкой на издание — не наблюдение ни при каком
    # сигнале: подпись «— Financial Times» в живом оповещении не встречается.
    if MEDIA_NEWS_RE.search(clean):
        observation.relevant = False
        return observation
    # Авиапроисшествие или удар по той стороне — новость, а не оповещение.
    if AIR_INCIDENT_RE.search(clean):
        observation.relevant = False
        return observation
    # Сводка за уже прошедший период: событие в ней закончилось до публикации.
    if RECAP_RE.search(clean) and signal in RECAP_CONTEXT:
        observation.relevant = False
        return observation
    # Дежурный доклад о тишине: события нет, класть на карту нечего.
    if threat == "unknown" and signal in QUIET_CONTEXT and QUIET_RE.search(clean):
        observation.relevant = False
        return observation
    # Новость про вооружение и намерения: тип угрозы назван, наблюдения нет.
    if MILITARY_NEWS_RE.search(clean) and signal in MILITARY_CONTEXT:
        observation.relevant = False
        return observation
    # Пересказ чужой войны: сильный сигнал там относится не к нашей карте.
    foreign = foreign_side(clean)
    if foreign and signal in RETRO_CONTEXT:
        observation.relevant = False
        return observation
    # Новостной текст без признаков обстановки — не наше событие.
    if NEWS_RE.search(clean) and signal in WEAK_CONTEXT:
        observation.relevant = False
        return observation
    # Статья с новостными маркерами или сводка последствий: сигнал в ней
    # пересказан, а не наблюдён. Объявленная тревога — исключение: канал
    # предупреждает о пусках подробно, называя чужой регион как точку старта
    # («Враг готовит массированные пуски от Харьковской области в сторону
    # Белгородской»), и такое оповещение терять нельзя.
    if signal != "alarm" and len(clean) > ARTICLE_LIMIT and (
        NEWS_RE.search(clean) or foreign or AFTERMATH_RE.search(clean)
    ):
        observation.relevant = False
        return observation
    # --- Прилёты не публикуются ---------------------------------------------
    #
    # Решение владельца от 13 августа, снижение правового риска: карта
    # предупреждает («прятаться или нет»), но не сообщает, КУДА попало.
    # Место прилёта — единственное, что давало карте ценность для оценки
    # результатов удара; предупреждающая функция держится на тревоге и
    # опасности и без неё не страдает.
    #
    # Снимаем слова удара и смотрим, что осталось в тексте, — тем же
    # приёмом, что у условного перехвата. По корпусу за неделю из 326
    # сообщений-ударов 274 (84%) не несут ничего, кроме удара: они уходят
    # целиком, и их текст не попадает даже в список источников. Остальные
    # 52 несут ещё перехват, тревогу или фиксацию — терять их нельзя, они
    # публикуются тем, что в них действительно есть.
    #
    # Правило стоит ПОСЛЕ всех защит от пересказов и сводок — на этом я
    # уже ошибся: стоя раньше, оно вытаскивало обратно новость «в Херсоне
    # зафиксированы пожары вследствие прилётов», потому что после снятия
    # слов удара в ней оставалось «зафиксированы» и получалась фиксация.
    if signal == "impact":
        rest = WEAK_IMPACT_RE.sub(" ", IMPACT_RE.sub(" ", clean))
        signal, severity = classify_signal(rest, observation.threat_type)
    if signal == "unknown":
        observation.relevant = False
        return observation
    # «Меры безопасности», «внимание по БПЛА», «не подходите к обломкам» —
    # призыв к бдительности, а не событие: решением владельца проекта класс
    # на карту не идёт вовсе. Сам паттерн из SIGNALS при этом не удалён
    # намеренно: без него «не подходите к обломкам БПЛА» переползало бы
    # через WEAK_SIGNALS в impact и красило район взрывом.
    if signal == "caution":
        observation.relevant = False
        return observation

    observation.signal_type = signal
    observation.severity = severity
    observation.threat_type = threat
    observation.direction_deg = extract_direction(clean)
    observation.target_count = extract_count(clean)
    observation.massive = is_massive(clean)
    observation.place_phrases = candidate_phrases(body)

    # Официальные врезки и групповые налеты весомее — но в пределах своей
    # полосы. Надбавка добавляет веса при сортировке, а не меняет цвет:
    # без потолка «Тревога» от МЧС уходила в красную полосу, а «Опасность»
    # с полусотней целей — в оранжевую, и подпись расходилась с заливкой.
    ceiling = band_ceiling(severity)
    if observation.official:
        observation.severity = min(ceiling, observation.severity + 1)
    # Групповой налёт весомее одиночного борта — что названный числом, что
    # словом. Вес тот же, но число целей больше не выдумывается ради него.
    if (observation.target_count and observation.target_count >= 5) or observation.massive:
        observation.severity = min(ceiling, observation.severity + 1)

    return observation
