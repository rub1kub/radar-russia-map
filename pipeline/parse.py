    r"|associated\s+press|\bcnn\b|\bbbc\b|the\s+guardian|forbes|axios|politico)"
    r"|\bразведк\w+\s+(?:сша|франци\w+|британи\w+|нато|запад\w+)"
    r"|что\s+позволи\w+|по\s+данным\s+(?:издания|газеты)|как\s+пишет\b"
