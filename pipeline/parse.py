"""Разбор текста сообщения в структурированное наблюдение.

Покрывает пять семейств форматов из docs/TARGET_ARCHITECTURE.md §4.
Текст канала — недоверенные данные: разбирается регулярными выражениями,
никогда не исполняется.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

from .textnorm import norm_key

# --- Футеры подписки --------------------------------------------------------
# Однозначные маркеры подписи: встречаются только в футере, длина строки
# роли не играет.
FOOTER_RE = re.compile(
    r"(подписаться|подписка|наш\s+канал|@[a-zA-Z_][a-zA-Z0-9_]{3,}"
    r"|локатор\s+россии|мониторинг\s+кубани|кубанский\s+вестник"
    r"|краснодарский\s+дозор|дозор\s+краснодара|в\s+ма[хx]\b)",
    re.IGNORECASE,
)

# Лента выросла с 12 источников до 74, и у каждого нового канала свой футер.
# Перечислять их по именам бессмысленно, поэтому ловим структурные признаки
# подписи: слово «радар»/«мониторинг» в названии канала, ссылку, зеркало в
# MAX, чат и обратную связь. Проверено по всей базе: в теле сообщений эти
# слова встречаются единицы раз (и там это тоже реклама канала).
# Снимать футер важно не ради чистоты: почти каждый содержит топоним
# («РОДНОЙ БЕЛГОРОД | РАДАР», «Радар ЛНР | Чат»), и geocode принимает его
# за место события, приклеивая чужой город к каждому сообщению канала.
FOOTER_BRAND_RE = re.compile(
    r"(https?://|\bt\.me/|maxln\.ru"
    r"|\bрадар\w*|\bмониторинг\w*|краснодарское\s+небо|ор[её]л\s+тревога"
    r"|\b[mм][aа][xх]\b|\b[mм][aа]кс(?:[еаому])?\b"
    r"|обратн\w+\s+связ|наш\s+чат|мы\s+в\s+telegram|читать\s+в\s+telegram"
    r"|дать\s+нам\s+голос|\bтг\b|по\s+данным\s+канал\w+"
    r"|поддержать\s+канал|слова\s+благодарности)",
    re.IGNORECASE,
)

# Футер — короткая строка-подпись: самый длинный настоящий футер в базе 77
# символов. Длинный абзац, где просто упомянуты «радар» или «обратная связь»,
# это текст сообщения, и вырезать его нельзя.
FOOTER_MAX_LEN = 100

# --- Ожидание отбоя, а не сам отбой -----------------------------------------
# «Оставайтесь в укрытии до сигнала "Отбой"», «укрытия не покидаем до отбоя»,
# «никакого отбоя нет» — это часть АКТИВНОГО оповещения. Без вырезания
# ракетная опасность по Орловской области уходила в allclear с severity 0,
# то есть тревога гасла ровно в момент объявления.
INSTRUCTION_RE = re.compile(
    r"(?:дождит\w+|ждите|жд[ёе]м|ожида\w+|получени[ияе])"
    r"[^\n]{0,30}?(?:отбо\w*|отмен\w+\s+(?:угроз|опасност|тревог))"
    r"|\bдо\s+(?:сигнала\s+)?[«\"']?отбо\w*|\bдо\s+[«\"']?отмены\b"
    r"|отбо\w*\s*(?:не\s+было|нет)|никакого\s+отбоя",
    re.IGNORECASE,
)

# --- Нерелевантное: политические и военные новости --------------------------
NEWS_RE = re.compile(
    r"\b(мид|зеленск\w+|путин\w*|минобороны|санкц\w+|саммит\w*|переговор\w+"
    r"|президент\w*|госдум\w+|заявил\w*|заявля\w+|сообщил\s+журналист"
    r"|написал\s+в\s+своем|подписал\s+закон|медведев\w*|песков\w*|лавров\w*"
    r"|трамп\w*|задержан\w*|росгвард\w+|военкомат\w*)\b",
    re.IGNORECASE,
)

# --- Нерелевантное: оборонная и военно-политическая новость ------------------
# «Полки беспилотных систем созданы в составе ВМФ России», «в состав ВМФ
# войдёт крейсер с гиперзвуковыми ракетами Циркон», «Иран пригрозил нанести
# ракетный удар» — рассказ про вооружение и намерения, а не наблюдение в небе.
# Тип угрозы в таком тексте назван («беспилотных», «ракетный»), глагола
# обстановки нет, и телеграфное правило делало из него detection/4. Места в
# сообщении тоже нет, поэтому событие ложилось на регион самого канала —
# фантомная фиксация БПЛА над Липецкой, Смоленской и Тульской областями.
#
# Ловим не сами слова «ВМФ», «ракета», «полк»: они есть и в оповещениях
# («работа ВКС по БПЛА», «хотят сорвать праздник ВМФ»). Ловим новостной
# оборот вокруг них — род войск как предмет сообщения, поставку техники,
# угрозу третьей страны и поздравление с военной датой.
#
# Названий кораблей («крейсер», «фрегат», «корвет», «подводная лодка») и
# «министра обороны» здесь намеренно нет, хотя оборонная новость их и полна.
# Это существительные, а не обороты: в приморских лентах корабль называют и
# в настоящем наблюдении («БЭК в направлении корвета»), а на Минобороны
# ссылается половина оповещений. Проверено по корпусу: ни одного сообщения
# они не ловят в одиночку — все три новости про «Циркон» уже опознаны по
# «в состав ВМФ» и «получивший наименование», а единственное совпадение с
# «министром обороны» и без того нерелевантно. Пользы нет, риск снять живое
# оповещение есть.
MILITARY_NEWS_RE = re.compile(
    r"в\s+состав\w*\s+(?:вмф|вкс|вмс|вдв|флот\w*|арми\w+|войск\w*)"
    r"|(?:созда\w+|сформирова\w+|развернут\w+)\s+в\s+составе"
    r"|\bглавком\w*|\bгенштаб\w*"
    r"|принят\w*\s+на\s+вооружени|поступ\w+\s+в\s+войск|встал\w*\s+на\s+боево"
    r"|получивш\w+\s+наименовани|пригроз\w+|намерен\w*\s+нанести"
    r"|поздравля\w+|\bс\s+праздником\b|\bс\s+дн[её]м\b|\bдень\s+военно",
    re.IGNORECASE,
)

# --- Нерелевантное: чужая сторона -------------------------------------------
# Сводки об ударах по Украине и ближневосточные новости приходят в те же
# ленты. Слова «прилёт», «пожар», «сбит» в них есть, а класть их на карту
# воздушной обстановки России некуда.
#
# Одного слова для опознания мало. Под «николаев\w*» в справочнике 543
# российские зоны (одна Николаевка встречается 309 раз), под «львов\w*» — 54,
# под «чернигов\w*» — 47: станица Львовская Краснодарского края уходила в
# нерелевантные вместе с работой МОГ. И наоборот: «Винницкое» и «Николаевка» —
# сёла Крыма, «Полтавская» — станица Кубани, «Новочеркасск» содержит
# «черкасс». Поэтому имена разделены на два списка, а решение принимается по
# совокупности признаков.

# Формы, которых российский тёзка не порождает: у села Киевское нет
# родительного «Киева», у хутора Харьковский — «Харькова», у Одесского района
# Омской области — «Одессы». Такое имя само называет чужой город.
#
# Косвенные падежи здесь обязательны: «кривой\s+рог» в именительном пропускал
# «прилёт по Эпицентру в Кривом Роге» и давал impact/9.
FOREIGN_CITY_RE = re.compile(
    r"\bкиев(?:а|е|у|ом)?\b|\bодесс(?:а|ы|е|у|ой)\b|\bхарьков(?:а|е|у|ом)?\b"
    r"|днепропетровск\w*|\bкрив(?:ой|ого|ому|ом|ым)\s+рог\w*|кривбасс\w*"
    r"|тегеран\w*|\bизраил(?:ь|я|ю|ем|е)\b|израильск\w*"
    r"|\bиран(?:а|у|е|ом)?\b|иранск\w*|ормузск\w+",
    re.IGNORECASE,
)

# Имена, у которых российские тёзки есть: Николаевка, Черниговка, станица
# Львовская, посёлок Черноморское, Херсонская и Запорожская области РФ.
# Само по себе такое слово не значит ничего — нужен второй признак.
FOREIGN_AMBIGUOUS_RE = re.compile(
    r"николаев\w*|чернигов\w*|львов\w*|черноморск\w*|херсон\w*|запорожь\w*"
    r"|киевск\w*|одесск\w*|харьковск\w*|каспийск\w+\s+мор\w+",
    re.IGNORECASE,
)

# Оборот, который прямо кладёт событие на украинскую землю. Слова «ВСУ» и
# «украинские БПЛА» в этот список не входят: ими описан и налёт на Ростов
# («Украинские БПЛА уничтожены над Орловской областью» — 43 таких сообщения),
# так что признаком чужой стороны они не являются.
FOREIGN_CONTEXT_RE = re.compile(
    r"контролируем\w+\s+(?:всу|украин\w*)|киевск\w+\s+режим|\bгсчс\b"
    r"|по\s+(?:территори|портам|объектам|городам|предприятиям)\w*\s+украин"
    r"|на\s+территории\s+украин|\bв\s+украине\b|вглубь\s+украин"
    r"|украинск\w+\s+(?:порт|полигон|город|территор|аэродром)"
    r"|порт\w*\s+[«\"']?(?:одесс|николаев|черноморск|измаил|южн)",
    re.IGNORECASE,
)

# Ленты новых регионов сами отделяют свою землю от чужой: «Херсонская область
# РФ», «Запорожская область РФ», «Николаевка, Береговое, Песчаное Республика
# Крым». Такая пометка рядом снимает подозрение с чужого имени: сообщение
# описывает нашу территорию, а чужой топоним в нём — точка старта или сосед.
#
# Вето сильное — оно перебивает даже однозначно чужой город, — поэтому в
# списке только явные пометки территории. «Кубань» отсюда убрана: это не
# пометка события, а самоназвание кубанских лент, и в футере «Оповещение
# Кубани» она снимала подозрение со сводок Минобороны об ударах по Одессе и
# Черноморску (5 сообщений корпуса). Футер такого вида strip_footer не режет,
# так что вето срабатывало на брендинге канала, а не на географии.
RUSSIAN_SIDE_RE = re.compile(
    r"област\w*\s+рф\b|\bлнр\b|\bднр\b|республик\w+\s+крым",
    re.IGNORECASE,
)

# --- Нерелевантное: сводка последствий --------------------------------------
# «Двое погибших, семеро ранены», «доставлен в областную больницу» — отчёт
# о вчерашнем налёте. Оповещение никогда не занимает 800 символов рассказа
# про больницы, а на карту такой текст положил бы событие задним числом.
AFTERMATH_RE = re.compile(
    r"госпитализир\w+|\bбольниц\w+|скор\w+\s+помощ|осколочн\w+\s+ранени"
    r"|получил\w*\s+ранени|пострадавш\w+\s+оказан|медицинск\w+\s+помощ"
    r"|выража\w+\s+(?:поддержк|соболезн)|склоняем\s+головы",
    re.IGNORECASE,
)

# --- Оговорка: канал сам не знает, что произошло ----------------------------
# «Новороссийск, уточняем характер взрыва» — это не сообщение о взрыве, а
# вопрос к самому себе; часом позже тот же куст лент написал, что по звукам
# всё штатно. Слово «взрыв» в такой фразе давало impact девятого уровня —
# высший на шкале, — и весь Краснодарский край окрашивался в красное.
#
# Ловится только прямая оговорка о самом событии. «По предварительной
# информации беспилотник атаковал автомобиль» под правило не попадает
# намеренно: там оговорка про подробности, а удар назван утвердительно.
UNCONFIRMED_RE = re.compile(
    r"уточня\w+\s+(?:характер|причин|информац|детал|что)"
    r"|проверя\w+\s+информац"
    r"|требует\w*\s+подтвержд"
    r"|характер\s+(?:взрыв|хлопк|звук)\w*\s+уточня",
    re.IGNORECASE,
)

# Во что превращается неподтверждённое «уже случилось». Событие не
# выдумано — канал что-то слышал, — но это ещё тревога, а не взрыв.
UNCONFIRMED_DOWNGRADE = {"impact": ("alarm", 7), "intercept": ("alarm", 7)}

# --- Нерелевантное: реклама канала ------------------------------------------
# «ВНИМАНИЕ! Идет массовая атака на регионы России. Просьба подписаться на
# канал и включить уведомления» — это объявление о самом канале, а не
# оповещение: места в нём нет, и на карту оно попадало по региону источника
# красной меткой над областью, под которой не выделено ни одного района.
#
# Обычную подпись в конце сообщения это не задевает: её снимает strip_footer,
# а здесь ловится призыв подписаться в самом теле.
PROMO_RE = re.compile(
    r"просьб\w*\s+подписа\w+|подпишитесь\s+на\s+канал|подписка\s+поможет"
    r"|включит[ье]\s+уведомлени|рекоменду\w+\s+подписа\w+"
    r"|подписаться\s*:?\s*https?://"
    r"|для\s+(?:оперативного\s+)?получения\s+\w+\s+оповещений"
    # Реклама сети «Город 24/7»: «ВНИМАНИЕ, ТРЕВОГА... Ищите свой регион и
    # подписывайтесь» со списком из 80 городов. Разбор поверил слову
    # «тревога» и влепил ракетную опасность почти везде — 168 ложных
    # событий одним сообщением.
    r"|подписывайтесь|ищите\s+свой\s+регион|не\s+будут\s+блокировать"
    r"|создать\s+телеграм\s+канал"
    # Оплаченная реклама в чужом канале. Маркировать её обязывает закон, и
    # маркировка — единственный надёжный признак: сам текст мимикрирует под
    # сводку. «Жителей Сочи предупреждают о необычном свечении... 65 минут
    # пролетят на одном дыхании» — реклама светового шоу, а на карте стояла
    # фиксация борта над Сочи, потому что «пролетят» неотличимо от пролёта.
    r"|#\s*реклам\w*|\berid\b|\bерид\b|промокод|по\s+промокоду",
    re.IGNORECASE,
)

# Канал говорит с подписчиками о самом канале: как ему присылать сообщения,
# что он отслеживает, сколько собрано на сбор. Такое объявление пересказывает
# лексику обстановки целыми абзацами — «о громких звуках, пролётах БПЛА и
# сбитиях сообщать в личные сообщения канала» — и разбор ставил по краю
# «Работу ПВО», хотя никто ничего не наблюдал.
CHANNEL_NOTICE_RE = re.compile(
    r"(?:дорог\w+|уважаем\w+)\s+(?:наши\s+)?(?:подписчик\w+|читател\w+|друз\w+|близк\w+)"
    r"|сообщат[ья]\s+в\s+личн\w+\s+сообщени"
    r"|(?:пишите|присылайте|отправляйте|скидывайте)\s+(?:нам\s+)?в\s+(?:личн\w+|бот|предложк\w+)"
    r"|мы\s+внимательно\s+отслежива\w+"
    r"|наш\w*\s+(?:канал\w*|подписчик\w+|читател\w+)\s+\w+",
    re.IGNORECASE,
)

# Больше стольких зон из одного сообщения — это каталог, а не оповещение:
# настоящая тревога не называет 80 городов разом. Сводки Минобороны с
# перечнем регионов режутся раньше, RECAP_RE; этот порог — последний рубеж
# против списков, которых мы ещё не видели.
MAX_RESOLVED_ZONES = 15

# --- Нерелевантное: подсчёт последствий -------------------------------------
# «10 погибших и 100 раненых при ударе по выставке под Киевом», «6 человек
# погибли, 26 пострадали» — это репортаж о случившемся, а не оповещение:
# живая сводка не считает погибших, она предупреждает. Отдельно от
# AFTERMATH_RE, потому что тот срабатывает только на длинном тексте, а
# заголовок новости укладывается в две строки и проходил как фиксация.
CASUALTY_RE = re.compile(
    r"\d+\s+(?:погибш|человек\s+погиб|раненых|пострадав)"
    r"|погиб\w*\s+\d+|ранен\w*\s+\d+\s+человек",
    re.IGNORECASE,
)

# Пересказ чужого репортажа: «кадры с места», «СМИ пишут». Не зависит от
# уровня сигнала — это разговор о событии, а не сообщение о нём.
REPORTAGE_RE = re.compile(
    r"кадр\w*\s+с\s+места|\bсми\s+(?:пишут|сообщ\w+)|видео\s+с\s+места"
    r"|появились\s+кадры|как\s+сообщ\w+\s+\w*\s*сми",
    re.IGNORECASE,
)

# --- Нерелевантное: аналитическая новость со ссылкой на СМИ -----------------
# «Разведки США и Франции предоставили Украине данные о расположении систем
# ПВО, что позволило составлять маршруты полётов БПЛА, — Financial Times».
# Слова «ПВО» и «БПЛА» здесь есть, глагола обстановки нет, места нет — и
# такой текст ложился работой ПВО на регион самого канала: над Волгоградской
# областью висела красная метка из газетной статьи.
#
# Ловим три признака пересказа, каждый сам по себе однозначен:
#   • подпись издания в конце («— Reuters», «, — Financial Times»);
#   • разведка или спецслужба чужой страны как субъект;
#   • оборот аналитики: «что позволило», «по данным издания», «как пишет»,
#     «планирует передать».
# Проверено по корпусу: правило гасит 5 новостей и не задевает ни одного
# живого оповещения — в том числе наблюдение за авиацией НАТО над морем,
# которое ловилось более широкой пробной версией и осталось на карте.
# Авиапроисшествие и рассказ про чужую сторону. «Российских дронов» —
# атакующие нас борта наши ленты российскими не называют: такое
# прилагательное значит, что речь про удар по той стороне. «Потерпел
