"""Дополнительные ограничения для общеновостных источников."""

from __future__ import annotations

import re


AIR_THREATS = frozenset({"uav", "fpv", "rocket", "kab", "bek", "aviation"})
OPASNOE_NEBO_RE = re.compile(r"\bопасное\s+небо\b", re.IGNORECASE)

# В общеновостной ленте одного слова «беспилотник» недостаточно: это может
# быть спорт, производство или памятка. Нужна формулировка живого сигнала.
EXPLICIT_ALERT_RE = re.compile(
    r"(?:"
    r"\b(?:беспилотн\w*|ракетн\w*|авиационн\w*)\s+опасност\w*"
    r"|\bвоздушн\w+\s+тревог\w*"
    r"|\bопасност\w*\s+(?:по\s+)?(?:бпла|дрон\w*|ракет\w*|авиац\w*)"
    r"|\bугроз\w*\s+(?:непосредственн\w+\s+)?(?:атак\w*|удар\w*)"
    r"|\b(?:атак\w*|нал[её]т\w*)\s+(?:вражеск\w+\s+)?(?:бпла|дрон\w*|беспилотник\w*)"
    r"|\b(?:бпла|дрон\w*|беспилотник\w*)\s+атак\w*"
    r"|\b(?:отраж\w*|подверг\w*)\s+[^.!?\n]{0,45}\bатак\w*"
    r"|\b(?:сбит\w*|уничтож\w*|перехвач\w*|ликвидирован\w*)\s+[^.!?\n]{0,35}"
    r"(?:бпла|дрон\w*|беспилотник\w*|ракет\w*)"
    r"|\b(?:бпла|дрон\w*|беспилотник\w*|ракет\w*)\s+[^.!?\n]{0,35}"
    r"(?:сбит\w*|уничтож\w*|перехвач\w*|ликвидирован\w*)"
    r"|\b(?:пво|рэб)\b\s+[^.!?\n]{0,50}(?:работ\w*|отраж\w*|сбил\w*|уничтож\w*)"
    r"|\b(?:работ\w*|силам\w*)\s+(?:систем\w+\s+)?(?:пво|рэб)\b"
    r"|\b(?:фиксац\w*|обнаруж\w*)\s+[^.!?\n]{0,35}(?:бпла|дрон\w*|беспилотник\w*)"
    r"|\b(?:падени\w*|обломк\w*|возгорани\w*)\s+[^.!?\n]{0,50}"
    r"(?:бпла|дрон\w*|беспилотник\w*)"
    r"|\bпопадан\w*\s+[^.!?\n]{0,35}(?:бпла|дрон\w*|беспилотник\w*)"
    r"|\b(?:бпла|дрон\w*|беспилотник\w*)\s+[^.!?\n]{0,35}попадан\w*"
    r"|\bотбой\b\s+[^.!?\n]{0,45}(?:опасност\w*|тревог\w*|угроз\w*)"
    r"|(?:опасност\w*|тревог\w*|угроз\w*)\s+[^.!?\n]{0,45}\bотмен\w*"
    r")",
    re.IGNORECASE,
)


def accepts_observation(observation, *, strict: bool = False) -> bool:
    """Разрешить наблюдение с учётом типа источника."""
    if not observation.relevant:
        return False
    if not strict:
        return True
    if OPASNOE_NEBO_RE.search(observation.body):
        return True
    if observation.threat_type not in AIR_THREATS:
        return False
    return bool(EXPLICIT_ALERT_RE.search(observation.body))
