"""Нормализация русских топонимов: slug, ключ сопоставления, варианты имени."""

from __future__ import annotations

import re
from functools import lru_cache

TRANSLIT = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "kh", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "shch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}

# Типовые части названий административных единиц и населенных пунктов.
# Сокращения перечислены без точки: strip_unit работает поверх norm_key,
# который пунктуацию уже убрал. Шаблон «г\.» здесь был мёртвым.
UNIT_WORDS = (
    "муниципальный округ", "городской округ", "городское поселение",
    "сельское поселение", "муниципальный район", "городской район",
    "автономный округ", "автономная область", "народная республика",
    "район", "округ", "область", "край", "республика", "поселение",
    "город", "пгт", "станица", "ст-ца", "поселок", "посёлок",
    "село", "деревня", "хутор", "аул", "слобода", "рп",
    "микрорайон", "мкр", "г",
)
UNIT_RE = re.compile(r"\b(" + "|".join(UNIT_WORDS) + r")\b", re.IGNORECASE)
PUNCT_RE = re.compile(r"[^\w\s\-]", re.UNICODE)
SPACE_RE = re.compile(r"\s+")

# Сокращения типа НП в тексте сводки. Однобуквенные раскрываются только с
# точкой и только перед словом: «с» без точки — предлог («с Азовского моря»),
# и без этого условия любой предлог объявлял бы следующее слово топонимом.
ABBREV_UNITS = {
    "г": "город", "гор": "город", "п": "поселок", "пос": "поселок",
    "пгт": "пгт", "рп": "рп", "с": "село", "ст": "станица",
    "ст-ца": "станица", "стца": "станица", "х": "хутор", "д": "деревня",
    "мкр": "микрорайон", "нп": "поселок", "р-н": "район", "р-он": "район",
}
# Требование заглавной буквы следом отсекает «10 г.» и прочие сокращения, за
# которыми названия нет. Проверка регистра локально снимает IGNORECASE — иначе
# она пропускала бы и строчную букву, то есть ничего бы не проверяла.
#
# Одной заглавной буквы мало: сокращение должно быть отдельным токеном.
# «(?<![\w-])» отсекает хвост чужого слова — «волна перемен с 90-х. Однако»
# давало «90-хутор Однако» и метило «Однако» как название НП. «(?<!т\.)»
# отсекает устойчивые «и т.д. Далее», «и т.п. Все»: там за точкой не топоним,
# а новое предложение. Осмысленные многочастные сокращения это не задевает —
# в «н.п. Шевченко» и «г.о.г. Липецк» перед буквой стоит «н.»/«о.», не «т.».
ABBREV_RE = re.compile(
    r"(?<![\w-])(?<!т\.)(" + "|".join(sorted(ABBREV_UNITS, key=len, reverse=True))
    + r")\.\s*(?=(?-i:[А-ЯЁA-Z]))", re.IGNORECASE,
)
# Без точки раскрываем только многобуквенные: «пгт Черноморское», «Мангушский р-н».
ABBREV_BARE_RE = re.compile(r"\b(пгт|мкр|рп|ст-ца|р-н|р-он)\b\.?", re.IGNORECASE)


def expand_units(text: str) -> str:
    """Раскрыть сокращения типа НП: «ст. Динская» -> «станица Динская».

    Нужно до norm_key: точка отличает сокращение от предлога, а norm_key её
    съедает. Полное слово потом работает маркером — за ним стоит название
    населённого пункта, а не одноимённой области.
    """
    text = ABBREV_RE.sub(lambda m: ABBREV_UNITS[m.group(1).lower()] + " ", text)
    return ABBREV_BARE_RE.sub(
        lambda m: ABBREV_UNITS.get(m.group(1).lower(), m.group(1)) + " ", text)


def slugify(text: str) -> str:
    """Латинский slug для стабильного zone_id."""
    lowered = text.lower().strip()
    out = []
    for char in lowered:
        if char in TRANSLIT:
            out.append(TRANSLIT[char])
        elif char.isalnum():
            out.append(char)
        elif char in " -_/":
            out.append("_")
    slug = "".join(out)
    slug = re.sub(r"_+", "_", slug).strip("_")
    return slug or "zone"


def norm_key(text: str) -> str:
    """Ключ сопоставления: без пунктуации, ё->е, э->е, схлопнутые пробелы.

    Схлопывание «э»->«е» лечит расхождение справочника и сводок: в исходных
    данных НП город записан как «Туапсэ», а каналы пишут «Туапсе», и 16
    сообщений про него не геокодировались вообще. Обе стороны нормализуются
    одинаково, так что Элиста и Энергодар от этого не страдают.
    """
    lowered = text.lower().replace("ё", "е").replace("э", "е").replace("​", " ")
    lowered = PUNCT_RE.sub(" ", lowered)
    return SPACE_RE.sub(" ", lowered).strip()


def strip_unit(text: str) -> str:
    """Убрать типовое слово: 'Азовский район' -> 'азовский'."""
    return SPACE_RE.sub(" ", UNIT_RE.sub(" ", norm_key(text))).strip()


# --- Лёгкий стеммер ---------------------------------------------------------
#
# Справочник хранит именительный падеж, а в сводках топоним почти всегда стоит
# в косвенном: «в Ростовской области», «по Краснодарскому краю», «над Анапой».
# Полноценная морфология (pymorphy) тянет внешнюю зависимость и словарь на
# десятки мегабайт, поэтому режем только типовые падежные окончания.
#
# Намеренно НЕТ «-ов»/«-ев»: это ядро сотен топонимов (Азов, Ростов, Тамбов),
# а родительный падеж множественного числа в сводках практически не встречается.
# Нет и «-ах»/«-ям»: множественное число для топонимов здесь редкость, а риск
# порчи имён (Байрам, Балахна) реальный.
#
# Группа «-ия/-ию/-ией» нужна целиком: одного «-ии» мало. Именительный
# «Евпатория» срезается по «-я» до «евпатори», а предложный «в Евпатории» —
# по «-ии» до «евпатор», и формы расходятся на одну букву. Тот же разрыв у
# Феодосии, Керчи-Ялты не касается, но накрывает весь женский тип на «-ия».
CASE_ENDINGS: tuple[str, ...] = (
    "ией",
    "ого", "его", "ому", "ему", "ыми", "ими",
    "ая", "яя", "ое", "ее", "ую", "юю", "ые", "ие", "ых", "их",
    "ым", "им", "ом", "ем", "ой", "ей", "ий", "ый", "ье", "ья", "ью", "ии",
    "ия", "ию",
    "а", "я", "о", "е", "у", "ю", "ы", "и", "ь", "й",
)
# Отсечение не должно превращать имя в огрызок: «Уфа» -> «уф», «Мга» -> «мг»
# дают массовые ложные совпадения. Три буквы — минимум, при котором «край» и
# «края» ещё сходятся в «кра», а трёхбуквенные имена остаются нетронутыми.
MIN_STEM = 3


@lru_cache(maxsize=200_000)
def stem_word(word: str) -> str:
    """Срезать одно падежное окончание.

    Один проход, а не до упора: «краснодарского» -> «краснодарск», а не
    «краснодар». Иначе прилагательные и существительные схлопнулись бы
    слишком сильно и потянули за собой чужие имена.

    Идемпотентности при этом нет и быть не может: «мария» -> «мари» -> «мар».
    Поэтому повторно стеммировать готовый ключ нельзя — вызывающий код должен
    сравнивать стем со стемом, а не со стемом от стема.
    """
    for ending in CASE_ENDINGS:
        if word.endswith(ending) and len(word) - len(ending) >= MIN_STEM:
            return word[: -len(ending)]
    return word


def stem_key(key: str) -> str:
    """Стеммированный ключ сопоставления: каждое слово по отдельности."""
    return " ".join(stem_word(word) for word in key.split())


# --- Род -------------------------------------------------------------------
#
# Стеммер схлопывает «Раевская» и «Раевский» в один ключ «раевск», и тёзка
# другого рода уводит разбор за полторы тысячи километров. Род словоформы
# из текста и род имени зоны должны совпадать.
#
# «-ой/-ей» здесь отнесены к женскому, хотя бывают и мужским именительным
# (Донской). Вызывающий код обязан применять фильтр по принципу «согласные
# или все», иначе такое имя потеряется.
FEMININE_FORMS = ("ая", "яя", "ую", "юю", "ой", "ей")
NEUTER_FORMS = ("ое", "ее")
MASCULINE_FORMS = ("ий", "ый")

# У имени род виден по последней букве: Раевская — ж, Мирное — с, Токмак — м.
FEMININE_NAMES = ("ая", "яя", "ья", "а", "я")
NEUTER_NAMES = ("ое", "ее", "о", "е")


def form_gender(word: str) -> str:
    """Род словоформы из текста: 'f', 'n', 'm' или '' — не определён.

    Пустая строка у «-ого/-ому/-ым/-ом» (мужской и средний неразличимы) и у
    множественного числа. Это не ошибка, а честное «не знаю»: такие формы
    фильтровать по роду нельзя.
    """
    if word.endswith(FEMININE_FORMS):
        return "f"
    if word.endswith(NEUTER_FORMS):
        return "n"
    if word.endswith(MASCULINE_FORMS):
        return "m"
    return ""


def name_gender(name: str) -> str:
    """Род имени зоны по последнему слову."""
    last = name.rsplit(" ", 1)[-1]
    if last.endswith(FEMININE_NAMES):
        return "f"
    if last.endswith(NEUTER_NAMES):
        return "n"
    return "m"


def name_variants(name: str, level: str) -> set[str]:
    """Набор ключей, по которым зону можно найти в тексте сообщения."""
    variants = {norm_key(name)}

    core = strip_unit(name)
    if core and len(core) >= 3:
        variants.add(core)

    # Дефис часто пишут по-разному: Ростов-на-Дону / Ростов на Дону.
    for variant in list(variants):
        if "-" in variant:
            variants.add(variant.replace("-", " "))

    return {v for v in variants if len(v) >= 3}
