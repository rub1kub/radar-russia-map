import { Info, X } from "lucide-react";

type Props = {
  open: boolean;
  onClose: () => void;
};

/**
 * Что это за карта и как она устроена.
 *
 * Методика была рассыпана по подсказкам, и сослаться на карту было не на
 * что: у сервиса, который просит доверия к «подтверждено восемью
 * источниками», обязана быть страница, где это правило записано словами.
 */
export function AboutPanel({ open, onClose }: Props) {
  if (!open) return null;

  return (
    <div
      className="analytics-overlay"
      role="dialog"
      aria-label="О проекте"
      onClick={(event) => {
        if (event.target === event.currentTarget) onClose();
      }}
    >
      <button className="analytics-close" type="button" onClick={onClose} aria-label="Закрыть">
        <X size={18} aria-hidden="true" />
      </button>

      <div className="analytics-card about-card">
        <div className="analytics-head">
          <Info size={17} aria-hidden="true" />
          <h2>О проекте</h2>
        </div>

        <p>
          Неофициальная карта воздушной обстановки, собранная по открытым
          Telegram-каналам: региональным радарам, официальным оповещениям
          МЧС и оперштабов, федеральным сводкам. Сообщения разбираются
          автоматически, без ручной модерации.
        </p>

        <h3>Как рождается событие</h3>
        <p>
          Из текста извлекаются место, тип сигнала и угрозы. Место ищется по
          справочнику из 212 тысяч зон — от субъекта до посёлка; тёзки
          разводятся контекстом сообщения и регионом самого канала.
          Сообщения об одном месте и одной угрозе склеиваются в одно событие.
        </p>

        <h3>Почему «источников» меньше, чем сообщений</h3>
        <p>
          Дословный перепост и каналы одной сети не считаются новым
          свидетельством: у сети один голос. Число под заголовком события —
          только независимые подтверждения, и каждое можно открыть и
          проверить по ссылке на оригинал.
        </p>

        <h3>Почему зона гаснет</h3>
        <p>
          Срок посчитан по физике, а не выдуман: ударный дрон идёт около
          150 км/ч, район в среднем 73 км в поперечнике, область — 416 км.
          Значит район борт пересекает примерно за полчаса, область — часа
          за три. Если новых сообщений нет дольше этого, борт зону уже
          покинул — и заливка гаснет. Ракета быстрее — её след гаснет
          быстрее.
        </p>

        <h3>Чего карта не умеет</h3>
        <p>
          Она опаздывает на время публикации и разбора, зависит от чужих
          сообщений и наследует их ошибки. Отбой показывается, когда каналы
          его прислали; когда не прислали — карта честно пишет, сколько
          молчит эфир. Это не система оповещения: решения о безопасности
          принимайте по указаниям экстренных служб.
        </p>

        <p className="about-foot">
          Код и данные открыты:{" "}
          <a
            href="https://github.com/rub1kub/radar-russia-map"
            target="_blank"
            rel="noreferrer noopener"
          >
            github.com/rub1kub/radar-russia-map
          </a>
        </p>
      </div>
    </div>
  );
}
