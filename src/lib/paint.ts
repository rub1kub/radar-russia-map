/**
 * Насколько густо красить зону.
 *
 * Цвет говорит, что происходит, а густота — насколько это касается именно
 * этого места и насколько это ещё в силе. Раньше густота зависела только от
 * числа событий, и карта врала дважды: субъект краснел целиком из-за одной
 * фиксации в одном районе, а тревога трёхчасовой давности горела так же
 * ярко, как минутная.
 */

/**
 * За сколько цель успевает покинуть зону такого размера. Те же числа, что в
 * api/server.py.
 *
 * Считается по тем аппаратам, которые здесь и летают: над нашей территорией
 * это украинские дальнобойные, и ленты их прямо называют — Хорнет, Бобр,
 * Дартс, Лютый, Рубака. Крейсерская у класса порядка 150 км/ч. Поперечник
 * зон по справочнику: район в среднем 73 км, регион 416 км — значит район
 * аппарат пересекает за полчаса, регион за три часа.
 */
export const ZONE_FADE_BY_LEVEL: Record<string, number> = {
  place: 15 * 60 * 1000,
  district: 30 * 60 * 1000,
  region: 165 * 60 * 1000
};
export const ZONE_FADE_MS = ZONE_FADE_BY_LEVEL.region;

/** Поправка на скорость цели относительно ударного дрона. */
export const THREAT_SPEED: Record<string, number> = {
  rocket: 0.2,
  aviation: 0.3,
  kab: 0.4,
  uav: 1,
  fpv: 1,
  bek: 2
};

/** Ниже этого зона не гаснет: событие ещё не закрыто. */
export const ZONE_FADE_FLOOR = 0.12;

/**
 * Насколько приглушается собственная заливка области, когда карта уже
 * работает на уровне районов.
 *
 * Вблизи сигнал — это район, а область лишь фон: тревога по ней объявлена,
 * но она кроет все районы разом. В полную силу этот фон забивал всё под
 * собой — район, погасший до 0.12, выглядел таким же красным, как соседний
 * горящий, потому что видно было не его, а область поверх.
 */
export const REGION_NEAR_WASH = 0.35;
/** Меньше этого срок не берём: сообщение и так приходит с задержкой. */
export const ZONE_FADE_MIN_MS = 8 * 60 * 1000;

export function fadeWindow(level?: string, threat?: string): number {
  const base = ZONE_FADE_BY_LEVEL[level ?? "district"] ?? ZONE_FADE_BY_LEVEL.district;
  return Math.max(ZONE_FADE_MIN_MS, base * (THREAT_SPEED[threat ?? "uav"] ?? 1));
}

/** Базовая густота по числу событий в зоне. */
export function zoneFillAlpha(active: number): number {
  if (active >= 5) return 0.42;
  if (active >= 3) return 0.3;
  return 0.19;
}

/**
 * Насколько зона выцвела ко времени просмотра.
 *
 * Кривая крутая в начале и пологая в конце — та же, что в api/server.py
 * zone_fade(). Линейная убыль оказалась слишком щадящей: за пятьдесят минут
 * без единого нового сообщения район терял всего четверть яркости и
 * выглядел как горящий сейчас. Человеку важна разница между «пять минут» и
 * «час», а между «два часа» и «три» — уже нет.
 *
 * Для района и ударного дрона: 5 минут — 0.59, 15 — 0.29, 30 — 0.12.
 */
export function freshness(
  lastActive: string | undefined,
  nowMs: number,
  level?: string,
  threat?: string
): number {
  if (!lastActive) return 1;
  const age = nowMs - new Date(lastActive).getTime();
  if (!Number.isFinite(age) || age <= 0) return 1;
  const share = Math.min(1, age / fadeWindow(level, threat));
  return Math.max(ZONE_FADE_FLOOR, 1 - share ** 0.5);
}

/**
 * Какая доля региона за заливкой стоит.
 *
 * Регион с собственным оповещением («опасность по области») закрашен в
 * полную силу. Регион, подсвеченный одной фиксацией в одном районе, —
 * почти прозрачен: иначе весь субъект краснеет из-за одного города, и
 * соседние районы, где ничего не происходит, читаются как такие же
 * опасные. Чем больше зон внутри горит, тем гуще заливка.
 */
export function regionWeight(own: number, active: number): number {
  if (own > 0) return 1;
  if (active >= 8) return 0.55;
  if (active >= 4) return 0.4;
  return 0.28;
}
