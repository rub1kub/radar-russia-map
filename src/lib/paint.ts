/**
 * Насколько густо красить зону.
 *
 * Цвет говорит, что происходит, а густота — насколько это касается именно
 * этого места и насколько это ещё в силе. Раньше густота зависела только от
 * числа событий, и карта врала дважды: субъект краснел целиком из-за одной
 * фиксации в одном районе, а тревога трёхчасовой давности горела так же
 * ярко, как минутная.
 */

/** Через сколько заливка выцветает до минимума. Тот же порог, что в
 *  api/server.py: карта показывает, что происходит, а не что случалось. */
export const ZONE_FADE_MS = 2 * 60 * 60 * 1000;
/** Ниже этого зона не гаснет: событие ещё не закрыто. */
export const ZONE_FADE_FLOOR = 0.12;

/** Базовая густота по числу событий в зоне. */
export function zoneFillAlpha(active: number): number {
  if (active >= 5) return 0.42;
  if (active >= 3) return 0.3;
  return 0.19;
}

/**
 * Насколько зона выцвела ко времени просмотра.
 *
 * Кривая крутая в начале и пологая в конце — та же, что в api/server.py
 * zone_fade(). Линейная убыль оказалась слишком щадящей: за пятьдесят минут
 * без единого нового сообщения район терял всего четверть яркости и
 * выглядел как горящий сейчас. Человеку важна разница между «пять минут» и
 * «час», а между «два часа» и «три» — уже нет.
 *
 * Пять минут — 0.80, полчаса — 0.50, час — 0.29, полтора — 0.13.
 */
export function freshness(lastActive: string | undefined, nowMs: number): number {
  if (!lastActive) return 1;
  const age = nowMs - new Date(lastActive).getTime();
  if (!Number.isFinite(age) || age <= 0) return 1;
  const share = Math.min(1, age / ZONE_FADE_MS);
  return Math.max(ZONE_FADE_FLOOR, 1 - share ** 0.5);
}

/**
 * Какая доля региона за заливкой стоит.
 *
 * Регион с собственным оповещением («опасность по области») закрашен в
 * полную силу. Регион, подсвеченный одной фиксацией в одном районе, —
 * почти прозрачен: иначе весь субъект краснеет из-за одного города, и
 * соседние районы, где ничего не происходит, читаются как такие же
 * опасные. Чем больше зон внутри горит, тем гуще заливка.
 */
export function regionWeight(own: number, active: number): number {
  if (own > 0) return 1;
  if (active >= 8) return 0.55;
  if (active >= 4) return 0.4;
  return 0.28;
}
