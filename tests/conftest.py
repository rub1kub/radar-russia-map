"""Общее для тестов, работающих на живом справочнике зон.

С русификацией справочника (9 августа) округа получили полные официальные
названия: «Анапа» стала «городским округом Анапа», «Тула» — «городским
округом Тула». Зона та же самая, идентификаторы сохранены намеренно
(коммит «Данные: сохранять стабильные ID зон при русификации»), но
проверки, сравнивавшие имя целиком, начали падать на формулировке.

Проверять разбор по имени по-прежнему нагляднее, чем по идентификатору, —
поэтому имя сравнивается без типового слова. Тест ловит разбор, а не то,
как справочник решил называть административную единицу.
"""

from __future__ import annotations

import re

# Типовое слово в начале официального имени: «городской округ Анапа».
ADMIN_HEAD = re.compile(
    r"^(?:городской|муниципальный|сельский)?\s*(?:округ|район|поселение)\s+",
    re.IGNORECASE)


def bare_name(name: str) -> str:
    return ADMIN_HEAD.sub("", name)
