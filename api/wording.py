"""Человеческие формулировки событий для уведомлений.

«Краснодар — инфраструктура, 13:51» не говорит человеку ничего:
«инфраструктура» — внутренний ярлык конвейера, а не сообщение. Здесь
каждый сигнал превращается в короткое предложение о том, что происходит:
«в небе видят БПЛА», «работает ПВО», «объявлена ракетная опасность».

Одни и те же слова получают и Telegram-бот, и веб-пуш — расходиться в
формулировках им незачем.
"""

from __future__ import annotations

# Кого видят в небе — винительный падеж после «видят».
_SEEN = {
    "uav": "БПЛА",
    "fpv": "FPV-дрон",
    "rocket": "ракету",
    "kab": "управляемую бомбу",
    "bek": "безэкипажный катер",
    "aviation": "авиацию",
}

# Какая объявлена опасность — так её называют сами оповещения.
_DANGER = {
    "uav": "опасность атаки БПЛА",
    "fpv": "опасность FPV-дронов",
    "rocket": "ракетная опасность",
    "kab": "опасность авиабомб",
    "bek": "опасность безэкипажных катеров",
    "aviation": "опасность авиации",
}


def event_sentence(event: dict) -> str:
    """Что происходит — одним коротким предложением, без места и времени."""
    signal = event.get("signal_type", "")
    threat = event.get("threat_type", "")
    cleared = event.get("status") == "resolved"

    if threat == "airport":
        return "аэропорт открыт" if cleared else "аэропорт закрыт"
    if signal == "infra":
        # Не-авиационная инфраструктура в корпусе — мост и дороги:
        # оба случая про перекрытое движение.
        return "движение открыто" if cleared else "перекрыто движение"
    if cleared or signal == "allclear":
        return "отбой"
    if signal == "detection":
        return f"в небе видят {_SEEN.get(threat, 'воздушную цель')}"
    if signal == "intercept":
        return "работает ПВО"
    if signal == "impact":
        return "сообщают о взрывах"
    if signal == "alarm":
        # Класс «тревога» — только явно объявленная воздушная/ракетная
        # тревога. Сирены, команды укрыться и неподтверждённые сообщения
        # остаются предупреждениями и сюда не попадают.
        if threat == "rocket":
            return "объявлена ракетная тревога"
        return "объявлена воздушная тревога"
    if signal == "danger":
        return f"объявлена {_DANGER.get(threat, 'опасность')}"
    return "изменение обстановки"
